defmodule BuildCalculator.TmpDir do
  @moduledoc """
  Уникальный путь к временному каталогу — переживает параллельные процессы
  `mix test` (партиции, несколько агентов на одной машине, CI).

  🔴 **Баг 3.192 → задача 3.194.** До этого модуля 34 места в `test/` строили
  путь `Path.join(System.tmp_dir!(), "rules_#{System.unique_integer([:positive])}")`
  каждое само. `System.unique_integer/1` уникален только ВНУТРИ ОДНОЙ VM — второй
  процесс `mix test` (другая партиция, другой агент на той же машине, CI-джоба)
  стартует свой счётчик с единицы и с высокой вероятностью получает **тот же
  путь**: один процесс копирует `priv/rules` в `rules_515`, второй его же удаляет
  своим `on_exit`, и первый падает `File.Error, "could not read file …: no such
  file or directory"`. Воспроизведено 12.09.2026 на первом же прогоне двух
  одновременных `mix test` с одним и тем же набором файлов — оба процесса
  получили путь `rules_515` (см. AGENT_QUEUE.md, 3.194).

  Путь несёт `:os.getpid()` этой ноды — PID уникален между процессами на одной
  машине (и с высокой вероятностью между машинами CI). `System.unique_integer/1`
  остаётся внутри пути, чтобы не сталкивать между собой несколько вызовов
  ОДНОГО теста/процесса.
  """

  @doc """
  Путь к ЕЩЁ НЕ СУЩЕСТВУЮЩЕМУ каталогу в `System.tmp_dir!/0`. Каталог не
  создаётся — вызывающий код сам решает, что туда положить (`File.cp_r!/2`,
  `File.mkdir_p!/1`…), и сам регистрирует `on_exit` на удаление.

  `prefix` уже несёт свой разделитель (`"rules_"`, `"gs-"`, `"spell-layer-"`),
  чтобы имя каталога совпадало по стилю с тем, что было в местах вызова
  до 3.194.
  """
  def unique_path!(prefix \\ "rules_") do
    Path.join(
      System.tmp_dir!(),
      "#{prefix}#{:os.getpid()}_#{System.unique_integer([:positive])}"
    )
  end
end
