defmodule BuildCalculator.Rules.MiniSets do
  @moduledoc """
  Мини-сеты: сколько кусков комплектов надето и во что это превращает
  оружейные и расовые бонусы шарда.

  Мини-сет — комплект предметов Сиалы; надетые куски ОДНОГО комплекта усиливают
  всё, что даёт система оружия и раса (задача 3.184, просьба Dan 11.09.2026:
  «я как раз хотел мини сеты добавить, потому что они очень распространены
  в реальной игре и нам они тоже нужны, просто их сложно было добавить без этих
  деталей»).

      B += floor(B · Nmini / 10)

  — после уровня, классовой группы и расового совпадения, **до** капа
  исполнителя. Ни одного числа здесь нет: делитель, счёт кусков, длина цикла
  слотов и кап каждого исполнителя приходят из
  `ruleset.shard_bonus_scaling` (`siala_41/systems.json` → `mini_sets` и
  `weapon_system.bonuses_level_tiers`).

  ## `Nmini` — счёт КУСКОВ, а не наборов

  Главная ловушка правила, и она стоит отдельным тестом:

      [A]          -> 0     одинокий кусок не считается ВООБЩЕ
      [A, B]       -> 0     два одиночки — тоже ноль
      [A, A]       -> 2
      [A, A, A]    -> 3
      [A, A, B]    -> 2     `B` один, его группа в сумму не входит
      [A, A, B, B] -> 4

  То есть `Nmini = Σ k[g]` по тем группам, где `k[g] > 1`. Ни «число надетых
  сетовых вещей», ни «число собранных наборов» — ни одно из двух привычных
  чтений не даёт верного числа.

  ⚠ **Идентичность набора для арифметики не нужна вовсе.** В сумму входит
  только мультимножество счётчиков, поэтому вход билда — список чисел
  (`Rules.Gear`'s `mini_sets`), а каталога из 80 групп в данных нет и заводить
  его незачем: имена понадобятся импорту игрового лога, а не расчёту.

  ## Почему усиление считается от СУММЫ, а не от каждого терма

  🔴 В движке расовый бонус и бонус за тип оружия — **один эффект**: исполнитель
  первым делом снимает прежний эффект своего типа и пишет свой, и `B` в формуле
  — итоговая величина этого эффекта. У нас это два независимых слагаемых,
  сходящихся в сумму (замер Dan 15.08.2026, `GAME_CHECKS.md` Q1: «30 БАБ +
  9 мод + 5 лук + 9 светлый эльф + 9 оружие дальнего боя = ровно 62»). Значит
  усиление обязано считаться от их суммы:

      база 12, три куска:   от суммы  12 + floor(36/10) = 15
                            по термам  6 + floor(18/10) = 7,  7 + 7 = 14

  Расхождение не гипотетическое: целочисленное деление усекает, и два усечения
  меньше одного. Ту же линию проводит кап исполнителя — он тоже на сумму.

  ## Два потолка на одно число, и это не дубль

  У исполнителя есть **свой, внутренний** кап (18 у атаки и щитового AC, 36
  у Дисциплины, у магического посоха — нет вовсе), и он не имеет отношения
  к ванильным `+20` на атаку и `+50` на бонусы к навыкам: первый принадлежит
  скрипту шарда и режет только эту систему, второй — правилам NWN и накрывает
  ещё и вещи. Клипы применяются по очереди, внутренний раньше.

  🔴 **До мини-сетов внутренний кап не кусал НИ РАЗУ, и потому его не было
  видно:** максимум формулы равен ему точка в точку (атака 9 + 9 = 18, щитовой
  AC 9 + 9 = 18, Дисциплина 18 + 18 = 36). Ровно это совпадение и было доводом
  «единица исполнителя» при переносе таблицы тиров (задача 3.181). С сетами
  кап режет постоянно, и цена его отсутствия — вдвое завышенное число
  у максимального билда.

  ## Что мини-сеты дают игроку — и почему это не то, чего ждёшь

  Билд 40-го уровня, бонус к атаке:

      обычный, оружие не расовое     6  ->  8 (4 куска)  ->  12 (10 кусков)
      сагровик, оружие не расовое    9  -> 12            ->  18
      обычный, расовое оружие       12  -> 16            ->  18
      сагровик + расовое оружие     18  -> 18            ->  18

  🔴 **Максимальному билду мини-сеты к этим бонусам не дают НИЧЕГО** — он
  упирается в кап и без них. Зато всем остальным дают до удвоения. Это надо
  уметь показать, иначе игрок сочтёт расчёт сломанным.

  ## Одна ветка усиления не получает

  Щитовой AC двулезвийного меча идёт **линейной** ветвью исполнителя AC
  (`ac_override`), и разбор скриптов говорит о ней прямо: «class, race, and
  mini-set transforms are bypassed». Мимо проходят ВСЕ множители, а не только
  расовый, поэтому её число не растёт от сетов и резать его нечем. Какую ветку
  берёт запись — данные (`executor` на строке), а не особый случай здесь.

  ## Что эта система даёт ещё, и где это живёт

  Мини-сеты дают ещё две вещи: **процент к HP** и **прибавку к скорости**.

  Первое считается с 11.09.2026 (задача 3.186) и живёт в своём модуле —
  `Rules.GearHitPoints`: у процента к HP **второй вход, которого у усиления
  нет вовсе** (крафтовые и уникальные вещи, `Ctotal = Cgear + Nmini`), своя
  нелинейная таблица и обрыв в ноль на одиннадцатой вещи. Общий у двух частей
  ровно один терм, `Nmini`, и он живёт здесь, где считается. ⚠ Оговорки
  `{:not_modelled, :mini_set_hp_bonus}` поэтому больше нет: мы это считаем,
  и продолжать признаваться значило бы пугать игрока тем, что уже сосчитано.

  Второе получателя не имеет вовсе: скорость бега калькулятор не считает,
  и по CLAUDE.md §9 дыры там нет.

  ⚠ **«Верхом» и «раненому» — это про HP, и ТОЛЬКО про него.** Разбор скриптов
  называет оба состояния внутри `ApplyMaxHPBonus` (`riding_factor` 0.5;
  раненому прибавка не применяется вовсе), а в арифметике восьми исполнителей
  (раздел 6 документа) ни одно из них не упоминается ни разу. Постановка задачи
  3.184 называла их оговорками к оружейным бонусам — здесь это поправлено
  по источнику, а сами два факта записаны в данных рядом с процентом к HP,
  где им и место.
  """

  alias BuildCalculator.Rules.{Build, RacialBonus, WeaponTypeBonus}

  @typedoc """
  Один получатель системы после усиления.

    * `executor` / `kind` / `skill` / `ac_type` — чей это эффект и куда он падает
    * `base` — сумма наших термов, как она считалась до мини-сетов
    * `added` — что прибавили куски, `0` без них
    * `clipped` — что снял ВНУТРЕННИЙ кап исполнителя, `0` или отрицательное
    * `total` — `base + added + clipped`
    * `capped?` — кап кусал
  """
  @type receiver :: %{
          executor: atom() | nil,
          kind: atom(),
          skill: atom() | nil,
          ac_type: atom() | nil,
          base: integer(),
          added: non_neg_integer(),
          clipped: integer(),
          total: integer(),
          capped?: boolean()
        }

  @doc """
  `Nmini` этого билда — сколько кусков идёт в счёт.

  Считаются только группы, у которых кусков не меньше `minimum_group` (двух),
  и считаются они **целиком**: два куска дают два, три — три. Одиночка
  не даёт ничего.

  ⚠ Клипается длиной цикла слотов (`slots`, одиннадцать): больше одиннадцати
  кусков надеть некуда, это число из самого скрипта, а не наше ограничение.

  `0`, если ruleset про мини-сеты не знает вовсе — тогда усиливать нечем,
  и билд, заявивший куски, говорит об этом гэпом (`gaps/2`). Умолчание
  направлено в сторону оговорки: снапшот без правила не имеет права молча
  начать умножать.
  """
  @spec pieces(Build.t(), map()) :: non_neg_integer()
  def pieces(%Build{gear: gear}, ruleset) do
    case rule(ruleset) do
      %{minimum_group: smallest, slots: slots} ->
        gear.mini_sets
        |> Enum.filter(&(is_integer(&1) and &1 >= smallest))
        |> Enum.sum()
        |> Kernel.min(slots)

      _no_rule ->
        0
    end
  end

  @doc """
  Все получатели системы у этого билда, по одному на эффект движка.

  Термы расового бонуса и бонуса за тип оружия складываются в один получатель
  тогда и только тогда, когда у них один **исполнитель** и один адресат
  (вид бонуса, навык, тип AC). Двулезвийный меч поэтому стоит отдельно
  от расового щитового AC: исполнитель у него линейный.

  `[]` — система ничего не даёт: нет её в ruleset'е, пусты руки, раса без
  бонуса. Ни одной оговорки на это не приходится, ровно как у
  `Rules.WeaponTypeBonus.of/2`.
  """
  @spec receivers(Build.t(), map()) :: [receiver()]
  def receivers(%Build{} = build, ruleset) do
    n = pieces(build, ruleset)

    for {key, base} <- terms(build, ruleset), do: amplify(ruleset, key, base, n)
  end

  @doc """
  Что мини-сеты добавляют к бонусу атаки — `0` без них.

  **Прибавка поверх наших двух термов, а не их замена:** `race_attack_bonus`
  и `weapon_type_attack_bonus` остаются тем, чем были, иначе разбор не смог бы
  назвать, из чего собралось число. Отрицательной величина быть может — это
  внутренний кап исполнителя, срезавший сумму.

  ⚠ **До ванильного потолка +20, как и оба усиливаемых терма.** Усиление стоит
  внутри того же выражения, которое страница объявляет входящим в лимит атаки
  («Бонус входит в лимита атаки +20»), то есть после усиления это тот же бонус,
  только больше. Сторона объявлена данными
  (`stat_caps.attack_bonus.applies_to_sources.mini_sets`), а не выведена здесь.
  """
  @spec attack_bonus(Build.t(), map()) :: integer()
  def attack_bonus(%Build{} = build, ruleset) do
    build
    |> receivers(ruleset)
    |> Enum.filter(&(&1.kind == :attack_bonus))
    |> Enum.reduce(0, &(&2 + delta(&1)))
  end

  @doc """
  Что мини-сеты добавляют к `skill` — `0` для всякого навыка, которого эта
  система не касается.

  Получателей сегодня четыре: Дисциплина (расовый бонус Человека и древковое
  оружие — один исполнитель, значит один получатель и одна сумма) и три навыка
  магического посоха. У посоха своего капа нет вовсе — единственный такой
  исполнитель из восьми, — поэтому там единственным потолком остаётся ванильный
  `+50` на пул бонусов к навыку, и он кусает по-настоящему.
  """
  @spec skill_bonus(Build.t(), map(), atom()) :: integer()
  def skill_bonus(%Build{} = build, ruleset, skill) do
    build
    |> receivers(ruleset)
    |> Enum.filter(&(&1.kind == :skill_bonus and &1.skill == skill))
    |> Enum.reduce(0, &(&2 + delta(&1)))
  end

  @doc """
  Что мини-сеты добавляют к классу брони — `[{kind, type, ac}]`, `[]` без них.

  Список и с `kind` — по тем же двум причинам, что у
  `Rules.WeaponTypeBonus.armor_class/2`: получателей может быть несколько,
  а `kind` нужен столкновению с числом, которое игрок вписал под тем же типом
  (`Rules.ArmorClass`). Здесь он всегда тот же, что у усиливаемого терма:
  усиление — тот же бонус, только больше, и правило столкновения у него не своё.
  """
  @spec armor_class(Build.t(), map()) :: [{atom(), atom() | nil, integer()}]
  def armor_class(%Build{} = build, ruleset) do
    for %{kind: :shield_ac = kind, ac_type: type} = receiver <- receivers(build, ruleset),
        ac = delta(receiver),
        ac != 0,
        do: {kind, type, ac}
  end

  @doc """
  Получатели вида «поглощение стихийного урона» после усиления — `[]`, если
  ни расовый бонус, ни оружие его не дают (задача 3.210).

  Список, а не одно число, по той же причине, что у `armor_class/2`: сколько
  эффектов движка сошлось в этот вид, решают данные, а не эта функция. Сегодня
  их не больше одного — исполнитель у расы Гнома и у группы топоров один
  (`:resistance`), значит и получатель один, и термы складываются **до**
  усиления (весь довод — в moduledoc).

  🔴 Отдаётся целиком, а не числом: `Rules.Resistances` печатает разбор, и ему
  нужны и сумма термов (`base`), и прибавка кусков (`added`), и то, что снял
  внутренний кап 36 (`clipped`). Число без них выглядело бы взявшимся из
  ниоткуда — ровно то, из-за чего усиление отдаётся отдельной строкой везде.
  """
  @spec damage_resistance(Build.t(), map()) :: [receiver()]
  def damage_resistance(%Build{} = build, ruleset) do
    build |> receivers(ruleset) |> Enum.filter(&(&1.kind == :damage_resistance))
  end

  @doc """
  Чего мини-сеты этого билда не говорят за себя.

    * `{:missing_data, :mini_set_counting}` — куски заявлены, снапшот **знает
      про систему оружия шарда**, а правила счёта у него нет: усиливать нечем,
      и число меньше игрового.

  ⚠ **Здесь была вторая форма — `{:not_modelled, :mini_set_hp_bonus}`** («куски
  дают ещё и проценты к HP, а мы их не считаем»). Снята 11.09.2026 задачей
  3.186 не вычёркиванием, а тем, что вернёт её само: процент считается
  (`Rules.GearHitPoints`), а снапшот без таблицы процентов получает
  `{:missing_data, :mini_set_hp_table}` и к HP не прибавляет ничего.

  🔴 **Ванильному ruleset'у не достаётся ни одной, и это не пропуск.** Мини-сетов
  в NWN нет вовсе — как нет ни расового бонуса шарда, ни бонуса за тип оружия, —
  поэтому заявленные там куски не значат ничего и оговаривать нечего. Разница
  между «системы нет» и «система есть, а правила счёта нет» читается по
  `shard_bonus_scaling`: у ванили его нет целиком, у снапшота Сиалы без правила
  он есть, а `mini_sets` в нём пуст. Сказать одно и то же про два разных
  состояния значило бы пугать ванильный билд правилом, которого в его правилах
  никогда и не было.

  ⚠ Прибавка к скорости оговорки не получает и не должна: скорость бега
  калькулятор не считает вовсе, получателя нет, и по CLAUDE.md §9 дыры там нет.
  """
  @spec gaps(Build.t(), map()) :: [tuple()]
  def gaps(%Build{gear: gear}, ruleset) do
    cond do
      gear.mini_sets == [] -> []
      not shard_system?(ruleset) -> []
      is_nil(rule(ruleset)) -> [{:missing_data, :mini_set_counting}]
      # Правило счёта есть — сказать нечего: усиление посчитано, процент к HP
      # посчитан соседним модулем. Это ОТВЕТ, а не забытая ветка.
      true -> []
    end
  end

  @doc """
  Сколько кусков персонаж может надеть вообще — длина цикла слотов
  исполнителя (одиннадцать: руки, пояс, сапоги, торс, плащ, голова, левая
  рука, оба кольца, шея). `nil`, если правила мини-сетов у ruleset'а нет.

  Числа игры не выдумывает никто, и веб-слой в том числе (CLAUDE.md §5), —
  поэтому потолок, которым `pieces/2` клипает сумму, отдаётся читателю
  геттером, а не переписывается вторым числом у поля ввода. Тот же приём,
  что у `Rules.Gear.hands/0` и `Rules.Caps.cap/2`: не расчёт, а доступ
  к тому, что правило уже прочитало.

  ⚠ Это НЕ запрет вводить больше. Расшаренная ссылка может нести что угодно
  и обязана открываться (`BuildCalculator.Encoding`), а сумма сверх потолка —
  повод предупредить, а не отказать: ровно та же линия, которой щит со вторым
  оружием остаётся записанным в билде и не идёт в числа (задача 3.132).
  """
  @spec slots(map()) :: pos_integer() | nil
  def slots(ruleset) do
    case rule(ruleset) do
      %{slots: slots} -> slots
      nil -> nil
    end
  end

  @doc """
  Сколько кусков ОДНОГО набора нужно, чтобы он пошёл в счёт (два). `nil`,
  если правила мини-сетов у ruleset'а нет.

  Отдаётся геттером по той же причине, что и `slots/1`: строка «1 кусок —
  в счёт не идёт» обязана назвать число, а числа игры веб-слой не выдумывает.
  🔴 И это единственное место, где `Nmini` расходится с наивным «сколько
  сетовых вещей надето»: одинокий кусок не даёт НИЧЕГО, а не «половину».
  """
  @spec minimum_group(map()) :: pos_integer() | nil
  def minimum_group(ruleset) do
    case rule(ruleset) do
      %{minimum_group: smallest} -> smallest
      nil -> nil
    end
  end

  # ------------------------------------------------------------------ private --

  # Есть ли у этого ruleset'а система, которую мини-сеты усиливают. У ванили
  # нет, и это единственный вопрос, который надо задать раньше всех остальных.
  defp shard_system?(ruleset), do: is_map(Map.get(ruleset, :shard_bonus_scaling))

  defp rule(ruleset) do
    case Map.get(ruleset, :shard_bonus_scaling) do
      %{mini_sets: %{} = rule} -> rule
      _absent -> nil
    end
  end

  defp delta(%{added: added, clipped: clipped}), do: added + clipped

  # Наши слагаемые, сгруппированные так, как их видит движок: по эффекту.
  # Порядок — первого появления, чтобы разбор печатался в том же порядке,
  # в каком считается.
  defp terms(build, ruleset) do
    entries =
      case RacialBonus.of(build, ruleset) do
        %{} = record -> [record | WeaponTypeBonus.of(build, ruleset)]
        nil -> WeaponTypeBonus.of(build, ruleset)
      end

    for %{counted: counted} = entry <- entries, is_integer(counted), reduce: [] do
      acc ->
        key = {entry.executor, entry.kind, entry.skill, entry.ac_type}

        case List.keyfind(acc, key, 0) do
          {^key, base} -> List.keyreplace(acc, key, 0, {key, base + counted})
          nil -> acc ++ [{key, counted}]
        end
    end
  end

  # Усиление и внутренний кап одного эффекта.
  #
  # ⚠ Кап применяется и при `Nmini = 0` — так его и описывает источник у атаки
  # и Дисциплины («cap 18», «cap 36», без оговорки про ветку). Без сетов он
  # не кусает ни на одном билде, потому что максимум формулы равен ему точка
  # в точку, и это под тестом с обеих сторон.
  #
  # ⚠ Исполнитель, которого таблица не описывает, не усиливается и не режется.
  # Гэпа на это нет намеренно: загрузчик роняет сборку на записи, у которой
  # число есть, а исполнителя нет, и на исполнителе, которого нет в таблице, —
  # то есть случай недостижим ни одним снапшотом, который вообще собрался.
  defp amplify(ruleset, {executor, kind, skill, ac_type}, base, n) do
    spec = executor_spec(ruleset, executor)
    added = added(spec, base, n, divisor(ruleset))
    capped = clamp(base + added, spec)

    %{
      executor: executor,
      kind: kind,
      skill: skill,
      ac_type: ac_type,
      base: base,
      added: added,
      clipped: capped - base - added,
      total: capped,
      capped?: capped != base + added
    }
  end

  defp executor_spec(ruleset, executor) do
    case Map.get(ruleset, :shard_bonus_scaling) do
      %{executors: %{^executor => spec}} -> spec
      _absent -> %{}
    end
  end

  # `floor(B · N / 10)`. ⚠ `div/2` усекает к нулю, а величины здесь
  # неотрицательные, так что это и есть floor — то же усечение, которым считает
  # NWScript и которое измерил замер `AM1`.
  defp added(%{mini_sets?: true}, base, n, divisor)
       when is_integer(divisor) and n > 0 and base > 0,
       do: div(base * n, divisor)

  defp added(_spec, _base, _n, _divisor), do: 0

  defp clamp(value, %{cap: cap}) when is_integer(cap) and value > cap, do: cap
  defp clamp(value, _spec), do: value

  defp divisor(ruleset) do
    case rule(ruleset) do
      %{divisor: divisor} -> divisor
      nil -> nil
    end
  end
end
