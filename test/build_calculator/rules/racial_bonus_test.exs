    test "поглощение урона и урон молчат, а не называются", %{ruleset: ruleset} do
      for race <- [:dwarf, :half_orc], level <- [1, 39, 40, 41] do
        stats = compute(ruleset, race, level)

        assert racial_gaps(stats) == [], "#{race} #{level}"

        # то же самое поимённо: ни старой формы, ни подмены её ветки ниже
        refute {:missing_data, {:racial_bonus_level, race}} in stats.gaps, "#{race} #{level}"

