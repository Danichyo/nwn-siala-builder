                 Map.fetch!(stated(ruleset, race), :racial_weapon_and_sagra_warrior),
               "#{race} #{level} оба"

        # Посчитанный вариант выбирается составом билда, а не уровнем.
        # ⚠️ 🔴 **У ОДНОЙ расы из пяти получателя нет вовсе — у Могучего
        # человека (урон), — и вариант у неё `nil`: не «не выбран», а «считать
        # некуда» (CLAUDE.md §9).** Здесь стояло «у двух из пяти»: поглощение
        # Гнома получателя не имело до 18.09.2026, а задача 3.210 завела секцию
        # «Резисты» (`DerivedStats.resistances`), и его 12/18 теперь считаются
        # ровно как щитовой AC Карлика. Молчание про УРОН при этом остаётся
        # решением и не должно исчезнуть заодно с правкой ступеней.
        expected =
          if kind in [:attack_bonus, :shield_ac, :skill_bonus, :damage_resistance],
            do: :sagra_warrior

        assert pure.variant == expected, "#{race} #{level}"
        assert mixed.variant == if(expected, do: :base), "#{race} #{level}"
      end
    end

    test "бонус к атаке, щитовой AC и Discipline на капе", %{ruleset: ruleset} do
      for level <- [40, 41] do
        assert compute(ruleset, :half_elf, level).race_attack_bonus == 9, "#{level}"
        assert Rules.compute(impure(:half_elf, level), ruleset).race_attack_bonus == 6, "#{level}"

        assert discipline(ruleset, :human, level).shard_race_bonus == 18, "#{level}"
        assert discipline_of(ruleset, impure(:human, level)).shard_race_bonus == 12, "#{level}"
      end
    end
  end

  # ------------------------------------------------------------------ helpers --

  # ⚠️ `vs_typed: :sum` — с задачи 3.91 у каждого терма есть поле «как он
  # встречается с числом, вписанным под тем же типом». У записи разметки это
  # всегда умолчание ruleset'а, то есть сумма; у сиальского щитового бонуса
  # ниже — `:max`, и разница между этими двумя строками и есть вся правка.
  #
  # ⚠️ Соседний хелпер `small_stature/0` (расовый размерный модификатор
  # Карлика/Гоблина, +1 AC) убран задачей 3.143 (30.08.2026): запись стала
  # `not_modelled` в `ac_bonuses.json`, своего терма больше не даёт ни на
  # одном билде, и хелпер, который печатал бы несуществующий терм, был бы
  # неверен молча.
  defp gnome_shield(ac),
    do: %{id: :gnome, source: {:race, :gnome}, type: :shield, ac: ac, vs_typed: :max}

  # Числа, написанные в файле, — чтобы кейс приёмки сверял ПОСЧИТАННОЕ
  # с ИСТОЧНИКОМ, а не с самим собой.
  defp stated(ruleset, race), do: ruleset.racial_bonuses.by_race[race].variants

  defp racial_gaps(stats),
    do: for(gap <- stats.gaps, inspect(gap) =~ "racial_bonus", do: gap)

  defp shard_race_ac_terms(stats),
    do: for(term <- stats.ac_own_terms, match?({:race, _}, term.source), do: term)

  # ⚠️ Уровни ВОИНА, то есть по умолчанию тут собирается воин Сагры (Fighter —
  # один из четырёх классов группы). Так было и до 08.08.2026, но тогда это ни
  # на что не влияло; теперь влияет на каждое число в файле, поэтому у каждого
  # есть парный кейс через `impure/2`.
  defp build(race, levels) when is_integer(levels) do
    %Build{} =
      Build.new(
        race: race,
        levels: List.duplicate(:fighter, levels),
        base_abilities: @flat,
        gear: Gear.new(@armed)
      )
  end

  # Тот же билд, но с пустыми руками — для кейсов про активацию.
  defp unarmed(%Build{} = build), do: %Build{build | gear: Gear.new([])}

  # Тот же билд той же длины, но последний уровень — бард: «любой другой класс в
  # билде нивелирует преимущества». Последний, а не первый, чтобы 1-й уровень
  # остался воинским — от класса первого уровня зависят цена и классовость
  # навыков, которые проверяет `discipline_of/2`.
  defp impure(race, levels) when is_integer(levels) do
    %Build{} =
      Build.new(
        race: race,
        levels: List.duplicate(:fighter, levels - 1) ++ [:bard],
        base_abilities: @flat,
        gear: Gear.new(@armed)
      )
  end

  defp compute(ruleset, race, levels), do: Rules.compute(build(race, levels), ruleset)

  # ⚠️ Оружие домешивается, а не задаётся вызывающим: без него `Gear.new/1`
  # затирал бы руки, бонус выключался, и кейс про ВЕЩИ зеленел бы по совершенно
  # другой причине — самый неприятный вид ложно-зелёного.
  defp geared(%Build{} = build, fields),
    do: %Build{build | gear: Gear.new(Keyword.merge(@armed, fields))}

  defp with_attack_cap(ruleset, cap),
    do: %{ruleset | stat_caps: Map.put(ruleset.stat_caps, :attack_bonus, cap)}

  # 4 ранга Discipline, купленные на 1-м уровне воина (классовый навык, цена 1).
  defp discipline(ruleset, race, levels), do: discipline_of(ruleset, build(race, levels))

  defp discipline_of(ruleset, %Build{} = base) do
    build = %Build{base | skills: %{1 => %{discipline: 4}}}

    Map.fetch!(Rules.compute(build, ruleset).skill_values, :discipline)
  end
end
