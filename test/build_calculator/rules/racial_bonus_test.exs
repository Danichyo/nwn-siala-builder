      # не включён, а Small stature с 3.143 не считается вообще.
      assert at_cap.ac_own_terms == []
      assert at_cap.ac_naked == 10

      # ⚠️ +9, а не +6: лестница набрана уровнями воина, то есть это сагровик
      # (решение Dan 08.08.2026). Парный кейс с бардом — сразу ниже.
      assert at_cap.ac_own_terms_geared == [gnome_shield(9)]

      assert at_cap.ac_own_bonus_geared == 9
    end

    # Тот же Карлик, чистота нарушена одним уровнем барда: щитовой терм не
    # исчезает, а уменьшается до базового +6. ⚠️ Сравнивается СПИСОК ТЕРМОВ,
    # а не итог: подмена варианта видна именно в терме, и порча «всегда брать
    # base» валит верхний кейс, а «всегда брать сагровика» — этот.
    test "у Карлика без чистоты щитовой терм базовый", %{ruleset: ruleset} do
      stats = Rules.compute(impure(:gnome, 41), ruleset)

      assert stats.ac_own_terms_geared == [gnome_shield(6)]
    end

    # Обратная половина того же правила, и без неё верхний кейс не доказывает
    # ничего: терм мог бы исчезнуть из голого числа по любой причине. Здесь он
    # исчезает и из «в шмоте» — ровно когда руки пусты.
    test "без оружия в руках щитового терма нет и в шмоте", %{ruleset: ruleset} do
      stats = Rules.compute(unarmed(build(:gnome, 41)), ruleset)

      assert stats.ac_own_terms_geared == []
      assert stats.ac_naked == 10
    end

    # Положительный контроль: раса без бонуса ничего к AC не получает.
    # ⚠️ До 3.143 здесь проверялось ещё и то, что `Small stature` у Гоблина
    # (точно такой же ванильный размерный модификатор, что у Карлика) не
    # путается со щитовым бонусом расы — не наш случай тут, раз Small stature
    # сам больше не считается ни у одной расы.
    # ⚠️ 11, а не 12: у Гоблина расовый модификатор +2 DEX (Halfling,
    # `vanilla/races.json`), у Карлика — +2 CON / −2 STR, ловкости он не даёт.
    test "у Гоблина того же размера щитового терма нет", %{ruleset: ruleset} do
      stats = compute(ruleset, :halfling, 41)

      assert stats.ac_own_terms == []
      assert stats.ac_naked == 11
    end

    # 🔴 Тип терма — `shield`, и это не украшение: «Этот класс брони не
    # складывается с бонусом класса брони щита, но складывается с базовым
    # классом брони щита». С задачи 3.39 это ПРАВИЛО, а не оговорка — вписанный
    # щит не прибавляется к расовому, а конкурирует с ним, и берётся большее.
    #
    # ⚠️ Здесь стояло `assert {:not_modelled, :ac_same_type_stacking}` — то есть
    # «мы складываем, а игра не складывает». Теперь проверяются числа.
    #
    # ⚠️ И вторая оговорка — про базу щита, которую «из одного введённого числа
    # не вычесть», — тоже снята: задача 3.41 сделала щит предметом с размером,
    # и база пришла из справочника (проверено ниже положительным контролем).
    test "щит с вещей и щит от расы не складываются — берётся большее", %{ruleset: ruleset} do
      with_shield = Rules.compute(geared(build(:gnome, 41), ac: %{shield: 4}), ruleset)
      no_shield = Rules.compute(geared(build(:gnome, 41), ac: %{armor: 8}), ruleset)

      # Карлик 41 воином — сагровик, расовый щитовой +9, плюс +9 за клинок
      # в руках. Вписанные 4 проигрывают им и в число не идут вовсе.
      assert with_shield.ac_by_type[:shield] == 0
      assert with_shield.ac_superseded_types == [:shield]
      assert with_shield.ac_geared == no_shield.ac_geared - 8

      refute {:not_modelled, {:ac_gear_base, :shield}} in with_shield.gaps

      # 🔴 Положительный контроль и главный смысл задачи 3.41: расовый щитовой
      # бонус побеждает вписанное число, а БАЗА выбранного щита прибавляется
      # СВЕРХ победителя — «не складывается с бонусом класса брони щита, но
      # складывается с базовым классом брони щита», дословно со страницы «Расы».
      # ⚠️ Задача 3.43 сменила здесь ДВЕ вещи, и обе — не про расовый бонус.
      # Щит СРЕДНИЙ, а не башенный: башенный Карлику носить нельзя вовсе
      # («gnomes and halflings may not use tower shields»). Топор РУЧНОЙ,
      # а не боевой: боевой — среднего размера, то есть для малой расы
      # двуручный, и щит рядом с ним не держится. Оба всё той же группы
      # владения и оба активируют расовый бонус, поэтому проверяемое
      # число не меняется. Сами запреты — в `wield_test.exs`.
      with_item =
        Rules.compute(
          geared(build(:gnome, 41),
            weapon: :handaxe,
            ac: %{shield: 4},
            worn: %{shield: :large}
          ),
          ruleset
        )

      assert with_item.ac_by_type[:shield] == 2
      assert with_item.ac_geared == with_shield.ac_geared + 2

      # ⚠️ Положительный контроль: доспех со щитовым бонусом не сталкивается —
      # разные типы складываются, как и складывались.
      assert Enum.filter(no_shield.gaps, &match?({_, {:ac_gear_base, _}}, &1)) == []
      assert no_shield.ac_by_type[:armor] == 8
    end
  end

