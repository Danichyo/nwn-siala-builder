    # dealing with larger creatures», и запись считалась безусловной. С 3.143
    # `small_stature` — `not_modelled` в обоих файлах (AC и атака), и терма
    # в `ac_own_terms`/`ac_own_terms_geared` больше нет ни на одном уровне —
    # эти списки ниже сравниваются ПОЛНОСТЬЮ, а не итогом, ровно поэтому
    # исчезновение своего терма и было поймано этим набором тестов.
