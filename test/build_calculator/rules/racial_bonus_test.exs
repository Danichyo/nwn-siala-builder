    test "молчат при любом оружии в руках", %{ruleset: ruleset} do
      hands = [
        {"пусто", []},
        {"топор", @armed},
        {"меч", [weapon: :longsword, feats: [:siala_blade_proficiency]]},
        {"трезубец", [weapon: :trident, feats: [:siala_polearm_proficiency]]}
