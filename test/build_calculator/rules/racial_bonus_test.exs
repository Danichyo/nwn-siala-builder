    #
    # Это правило CLAUDE.md §9, которым с экрана снята бо́льшая часть из 89
    # классовых фактов (нашего получателя несут 19): **гэп — дырка
    # в нашем ОТВЕТЕ, а не в наших знаниях.** Числа на 40-м известны (12/- и +6
    # урона), но ни строки урона, ни строки поглощения в билде нет — значит вопрос
    # такой не задан, и дырки нет. Заодно исчезла асимметрия: оружейная половина
    # той же системы (`Rules.WeaponTypeBonus`) про эти же виды уже молчала.
    #
    # ⚠️ Уровни взяты по обе стороны от 40-го НЕ для симметрии: молчание обязано
