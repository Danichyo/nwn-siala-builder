    # правда. Рисует справку веб-слой (`Labels.gap/2`), но взять её ему негде.
    test "все четыре числа доезжают до билда", %{ruleset: ruleset} do
      bonus = compute(ruleset, :half_elf, 41).racial_bonus

      assert bonus.variants == %{
               base: 6,
               sagra_warrior: 9,
               racial_weapon: 12,
               racial_weapon_and_sagra_warrior: 18
             }

      assert bonus.counted == 9
      assert bonus.variant == :sagra_warrior
      assert bonus.kind == :attack_bonus
      assert bonus.stated_for_level == 40
      assert bonus.cap == :attack_bonus
      assert bonus.modelled?
    end

    # ⚠️ **Два варианта из четырёх не считаются ЗДЕСЬ, и не должны** — с
    # 15.08.2026 это утверждение про ЭТОТ модуль, а не про модель. Замер Dan
    # показал, что оба — СУММЫ: расовый бонус плюс бонус за тип оружия
    # (`30 + 9 + 5 + 9 + 9 = 62` у светлого эльфа-сагровика с луком +5). Значит
    # их числа приедут арифметикой, как только заведут второй терм (задача 3.35),
    # и третье чтение здесь удвоило бы бонус каждому эльфу с луком.
    #
    # Проверяется не «варианты лежат в структуре» (это выше), а что ни одно из
    # двух оружейных чисел не попало в АРИФМЕТИКУ ни у одного билда — включая
    # чистого сагровика, у которого половина условия выполнена.
    test "оружейные варианты не берутся никогда", %{ruleset: ruleset} do
      for levels <- [40, 41], race <- [:half_elf, :gnome, :human] do
        bonus = compute(ruleset, race, levels).racial_bonus
        weapon = [bonus.variants.racial_weapon, bonus.variants.racial_weapon_and_sagra_warrior]

        assert bonus.variant == :sagra_warrior, "#{race} #{levels}"
        refute bonus.counted in weapon, "#{race} #{levels}: посчитан оружейный вариант"
      end
    end

    # ⚠️ Условие варианта читается ИЗ ДАННЫХ, а не зашито в ядро: `races.json`
    # называет условие тем же словом, что и вариант (`sagra_warrior`), и цитирует
    # страницу группы, а `systems.json` и страницы классов говорят, кто в группу
    # входит. Ядро только сопоставляет. Если эта связка развалится, вариант
    # перестанет применяться — а не «применится к кому попало».
    test "условие варианта связано с группой классов данными", %{ruleset: ruleset} do
      assert ruleset.racial_bonuses.conditions == %{
               sagra_warrior: {:class_group, :sagra_warriors}
             }

      assert ruleset.racial_bonuses.variant_conditions == %{
               base: [],
               sagra_warrior: [:sagra_warrior],
               racial_weapon: [:racial_weapon],
               racial_weapon_and_sagra_warrior: [:racial_weapon, :sagra_warrior]
             }
    end
  end

  describe "данные" do
    test "все пять записей разобраны, у обеих рас без бонуса записи нет", %{ruleset: ruleset} do
      by_race = ruleset.racial_bonuses.by_race

      assert Map.keys(by_race) |> Enum.sort() == [:dwarf, :gnome, :half_elf, :half_orc, :human]

      for {race, record} <- by_race do
        assert map_size(record.variants) == 4, "#{race}"
        assert record.status == "verified", "#{race}"
      end
    end

    # ⚠️ Здесь стоял тест «отсутствие формулы роста — гэп ruleset'а»
    # (`assert {:missing_data, :racial_bonus_progression} in ruleset.gaps`).
    # **Форма снята 22.08.2026 решением Dan** (задача 3.81): «прогрессию делать
    # не будем, данный пробел можно закрыть» — продолжение решения Q2, где
    # добывание прогрессии было закрыто целиком.
    #
    # Утверждение про ДАННЫЕ осталось и проверяется по-прежнему: формулы в файле
    # нет, и это по-прежнему верно — изменилось только то, что мы про это больше
    # не признаёмся ruleset-гэпом, потому что признание было про полноту наших
    # данных, а не про наш ответ.
    test "формулы роста в данных нет — и это больше не гэп ruleset'а", %{
      ruleset: ruleset,
      vanilla: vanilla
    } do
      assert ruleset.racial_bonuses.formula == nil

      refute Enum.any?(ruleset.gaps, &match?({:missing_data, :racial_bonus_progression}, &1))
      refute Enum.any?(vanilla.gaps, &match?({:missing_data, :racial_bonus_progression}, &1))

      # и вторая половина той же системы ушла тем же решением — они одно правило
      refute Enum.any?(ruleset.gaps, &match?({:missing_data, :weapon_type_bonus_progression}, &1))
    end

    # 🔴 **ГЛАВНЫЙ тест задачи 3.81, и он про то, чего решение НЕ отменяет.**
    # Снят гэп КОРПУСА («таблицы роста у нас нет»); гэп БИЛДА («на ЭТОМ билде
    # бонус не посчитан») остаётся, потому что бонус в игре есть, а величины его
    # не знает никто — CLAUDE.md §3 говорит это дословно.
    #
    # Цена ошибки измерена, а не предположена: у светлого эльфа-воина 25-го
    # уровня с луком AB равен голому BAB, то есть **вдвое** меньше, чем на 40-м
    # (23 против 48 — расовый +9 и оружейный +9 там оба выключены). Эти две
    # оговорки — единственное, что говорит игроку, почему. Прочитай кто-нибудь
    # «убрали прогрессии» шире, чем сказано, — и билд ниже 40-го начнёт занижать
    # AB молча.
    # ⚠️ ЛУК, а не дефолтный топор из `@armed`: топор выбран нейтральным нарочно
    # (его бонус — поглощение урона, получателя в билде нет), и на нём вторая
    # половина утверждения была бы непроверяемой. Лук даёт AB, то есть обе
    # оговорки падают в одно и то же число.
    test "решение 3.81 сняло гэп корпуса и не тронуло гэп билда", %{ruleset: ruleset} do
      bow = [weapon: :longbow, feats: [:siala_ranged_proficiency]]

      at_25 = Rules.compute(geared(build(:half_elf, 25), bow), ruleset)
      at_40 = Rules.compute(geared(build(:half_elf, 40), bow), ruleset)

      assert {:missing_data, {:racial_bonus_level, :half_elf}} in at_25.gaps
      assert {:missing_data, {:weapon_type_bonus_level, :longbow}} in at_25.gaps

      # и это именно про непосчитанное число, а не про молчание: бонусов нет,
      # AB равен базовой атаке
      assert at_25.race_attack_bonus == 0
      assert at_25.attack_bonus == at_25.base_attack

      # положительный контроль: на 40-м обоих гэпов нет, а числа посчитаны
      refute {:missing_data, {:racial_bonus_level, :half_elf}} in at_40.gaps
      refute {:missing_data, {:weapon_type_bonus_level, :longbow}} in at_40.gaps
      assert at_40.race_attack_bonus == 9
      assert at_40.attack_bonus - at_40.base_attack == 18
    end

    # Число потолка написано в двух файлах, и они обязаны совпадать: страница
    # расы говорит «кап атаки +20», а режет ядро тем, что лежит в
    # `overrides.json`. Разойдись они — интерфейс называл бы потолок, которым
    # арифметика не пользуется.
    test "потолок из races.json совпадает с тем, которым режет ядро", %{ruleset: ruleset} do
      assert ruleset.racial_bonuses.by_race[:half_elf].counts_toward_cap == :attack_bonus
      assert ruleset.stat_caps.attack_bonus == 20

      assert ruleset.racial_bonuses.by_race[:human].counts_toward_cap == :skill_bonus
      assert ruleset.stat_caps.skill_bonus == 50
    end
  end

  # ------------------------------------------------------------------ helpers --

  # ⚠️ `vs_typed: :sum` — с задачи 3.91 у каждого терма есть поле «как он
  # встречается с числом, вписанным под тем же типом». У записи разметки это
  # всегда умолчание ruleset'а, то есть сумма; у сиальского щитового бонуса
  # ниже — `:max`, и разница между этими двумя строками и есть вся правка.
  #
  # ⚠️ Соседний хелпер `small_stature/0` (расовый размерный модификатор
  # Карлика/Гоблина, +1 AC) убран задачей 3.143 (30.08.2026): запись стала
  # `not_modelled` в `ac_bonuses.json`, своего терма больше не даёт ни на
  # одном билде, и хелпер, который печатал бы несуществующий терм, был бы
  # неверен молча.
  defp gnome_shield(ac),
    do: %{id: :gnome, source: {:race, :gnome}, type: :shield, ac: ac, vs_typed: :max}

  defp racial_gaps(stats),
    do: for(gap <- stats.gaps, inspect(gap) =~ "racial_bonus", do: gap)

  defp shard_race_ac_terms(stats),
    do: for(term <- stats.ac_own_terms, match?({:race, _}, term.source), do: term)

  # ⚠️ Уровни ВОИНА, то есть по умолчанию тут собирается воин Сагры (Fighter —
  # один из четырёх классов группы). Так было и до 08.08.2026, но тогда это ни
  # на что не влияло; теперь влияет на каждое число в файле, поэтому у каждого
  # есть парный кейс через `impure/2`.
  defp build(race, levels) when is_integer(levels) do
    %Build{} =
      Build.new(
        race: race,
        levels: List.duplicate(:fighter, levels),
        base_abilities: @flat,
        gear: Gear.new(@armed)
      )
  end

  # Тот же билд, но с пустыми руками — для кейсов про активацию.
  defp unarmed(%Build{} = build), do: %Build{build | gear: Gear.new([])}

  # Тот же билд той же длины, но последний уровень — бард: «любой другой класс в
  # билде нивелирует преимущества». Последний, а не первый, чтобы 1-й уровень
  # остался воинским — от класса первого уровня зависят цена и классовость
  # навыков, которые проверяет `discipline_of/2`.
  defp impure(race, levels) when is_integer(levels) do
    %Build{} =
      Build.new(
        race: race,
        levels: List.duplicate(:fighter, levels - 1) ++ [:bard],
        base_abilities: @flat,
        gear: Gear.new(@armed)
      )
  end

  defp compute(ruleset, race, levels), do: Rules.compute(build(race, levels), ruleset)

  # ⚠️ Оружие домешивается, а не задаётся вызывающим: без него `Gear.new/1`
  # затирал бы руки, бонус выключался, и кейс про ВЕЩИ зеленел бы по совершенно
  # другой причине — самый неприятный вид ложно-зелёного.
  defp geared(%Build{} = build, fields),
    do: %Build{build | gear: Gear.new(Keyword.merge(@armed, fields))}

  defp with_attack_cap(ruleset, cap),
    do: %{ruleset | stat_caps: Map.put(ruleset.stat_caps, :attack_bonus, cap)}

  # 4 ранга Discipline, купленные на 1-м уровне воина (классовый навык, цена 1).
  defp discipline(ruleset, race, levels), do: discipline_of(ruleset, build(race, levels))

  defp discipline_of(ruleset, %Build{} = base) do
    build = %Build{base | skills: %{1 => %{discipline: 4}}}

    Map.fetch!(Rules.compute(build, ruleset).skill_values, :discipline)
  end
end
