defmodule BuildCalculator.Rules.RacialBonusTest do
  @moduledoc """
  Расовый бонус Сиалы (задача 3.12) — таблица кейсов по одному источнику.

  Все числа со страницы `Расы` вики Сиалы, `revid 16292`, перенесены в
  `priv/rules/siala_41/races.json` целиком:

  | раса (ru / en)           | вид                | base | сагровик | расовое оружие | оба |
  |--------------------------|--------------------|------|----------|----------------|-----|
  | Светлый эльф / Half-elf  | бонус к атаке      |   +6 |       +9 |            +12 | +18 |
  | Карлик / Gnome           | щитовой AC         |   +6 |       +9 |            +12 | +18 |
  | Человек / Human          | +к Discipline      |  +12 |      +18 |            +24 | +36 |
  | Гном / Dwarf             | поглощение урона   |  +12 |      +18 |            +24 | +36 |
  | Могучий человек/Half-orc | бонус к урону      |   +6 |       +9 |            +28 | +40 |
  | Гоблин / Halfling        | нет вовсе          |    — |        — |              — |   — |
  | Тёмный эльф / Elf        | нет вовсе          |    — |        — |              — |   — |

  ⚠️ **Числа верны ровно для 40-го уровня персонажа**, и это не оговорка, а
  главное свойство правила: «На первых уровнях персонажа бонус от расы невелик,
  но постепенно с набором уровней он увеличивается. Бонус становится максимальным
  на 40 уровне». Функции роста нет ни на одной странице, поэтому ниже 40-го ядро
  не считает ничего и говорит почему.

  ⚠️ **Считаются ДВА варианта из четырёх, и какой именно — решает состав билда**
  (решение Dan 08.08.2026: «сагровик получит больше бонусов, чем несагровик»):
  `sagra_warrior` у билда, все уровни которого взяты из классов Сагры, и `base`
  у всех остальных. Два оставшихся не считаются здесь и не должны: замер Dan
  15.08.2026 (`GAME_CHECKS.md` Q1) показал, что это СУММЫ двух независимых
  термов — расового бонуса и бонуса за ТИП оружия, — и второй считает
  `Rules.WeaponTypeBonus` с задачи 3.35. ⚠️ Здесь стояло «оружие не моделируется
  вовсе (армори, задача 3.5)»: посылка устарела дважды, вывод — нет, поэтому
  показанное число остаётся полом и у сагровика тоже.

  ⚠️ **Про посчитанный вариант ядро с 25.08.2026 МОЛЧИТ** (задача 3.102, решение
  Dan): «посчитан вариант сагровика +9» — ответ, а не дырка, и печатать его
  в списке гэпов билда значило спорить с заголовком «ядро не смогло посчитать N».
  Предложение никуда не делось — оно печатается справкой у самого числа
  (`Summary.racial_bonus_note/2`, тесты в `racial_bonus_note_test.exs`). Гэпов
  тут осталось два, и оба про настоящую недостачу: уровень ниже того, для
  которого числа названы, и пустые руки.

  ⚠️ **Поэтому у каждого числа здесь есть парный кейс с нарушенной чистотой.**
  Хелпер `build/2` набирает уровни ВОИНА, то есть по умолчанию собирает
  сагровика; `impure/2` подменяет последний уровень бардом и тем самым отменяет
  группу. Пара нужна не для симметрии: без неё тест зеленел бы и у кода, который
  всегда берёт вариант сагровика.
  """
  use ExUnit.Case, async: true

  alias BuildCalculator.Data
  alias BuildCalculator.Rules
  alias BuildCalculator.Rules.{Build, Gear, RacialBonus}

  @flat %{str: 10, dex: 10, con: 10, int: 10, wis: 10, cha: 10}

  # ⚠️ **Оружие в руках — не декорация кейса, а условие самого бонуса** (замер Dan
  # 15.08.2026, `GAME_CHECKS.md` Q1/Q4): голый светлый эльф-сагровик 40 показывает
  # в игре AB 29, то есть без оружия расового бонуса нет вовсе. До этого дня
  # правило лежало прозой в `races.json` → `activation` и ядром не читалось.
  #
  # Поэтому каждый кейс этого файла, который спрашивает «какое число», обязан
  # держать оружие; кейсы «включается ли» живут отдельным блоком ниже и оружие
  # снимают.
  #
  # 🔴 **ТОПОР, а не меч, и это правка 16.08.2026 (задача 3.35).** Здесь стоял
  # `longsword` с доводом «клинковое — не расовая группа ни для одной из
  # проверяемых здесь рас, значит бонус за ТИП оружия сюда не примешивается».
  # Довод был неверен: бонусу за тип оружия раса безразлична — клинок даёт
  # щитовой AC КОМУ УГОДНО, — и с задачей 3.35 длинный меч добавил бы каждому
  # билду этого файла +9 щитового AC поверх расового. Нейтральное оружие — то,
  # чей бонус не имеет получателя в билде вовсе: топоры (поглощение урона) и
  # молоты (звуковой урон). Боевой топор включает расовый бонус («любое оружие
  # в руках») и не двигает ни одного числа сам.
  @armed [weapon: :battleaxe, feats: [:siala_axe_proficiency]]

  setup_all do
    %{ruleset: Data.ruleset!("siala_41"), vanilla: Data.ruleset!("vanilla")}
  end

  describe "уровень, на котором бонус вообще известен" do
    # Fighter 40 → base attack 20 за первые 20 уровней + 10 эпических = 30.
    # Fighter 41 → 41-й нечётный, значит +1 к атаке (vanilla/epic.json,
    # подтверждено Даном для 41-го): 31.
    #
    # ⚠️ Проверяются ОБА уровня, и главное здесь — что бонус НЕ вырос: «Бонус
    # становится максимальным на 40 уровне», значит на 41-м он тот же, а не
    # больше. Растёт только сама база атаки.
    #
    # ⚠️ +9, а не +6: билд набран уровнями воина, то есть это чистый сагровик
    # (решение Dan 08.08.2026). Парный кейс с нарушенной чистотой — ниже.
    test "на 40-м и 41-м уровне бонус к атаке одинаковый", %{ruleset: ruleset} do
      at_40 = compute(ruleset, :half_elf, 40)
      at_41 = compute(ruleset, :half_elf, 41)

      assert {at_40.base_attack, at_40.race_attack_bonus, at_40.attack_bonus} == {30, 9, 39}
      assert {at_41.base_attack, at_41.race_attack_bonus, at_41.attack_bonus} == {31, 9, 40}

      # то же самое, сказанное про сам бонус, а не про сумму: он не изменился
      assert at_41.race_attack_bonus == at_40.race_attack_bonus
      assert at_41.attack_bonus - at_40.attack_bonus == 1
    end

    # ⚠️ Тот же билд, у которого последний уровень отдан барду: одного чужого
    # уровня достаточно, чтобы группа отменилась («любой другой класс в билде
    # нивелирует преимущества»), и вариант возвращается к базовому +6.
    #
    # Это положительный контроль ко всему файлу: без него все числа выше зеленели
    # бы и у кода, который берёт вариант сагровика всегда. База атаки при этом
    # тоже меняется (бард даёт 3/4), поэтому сверяется не разность сумм, а сам
    # расовый бонус — и он ровно на 3 меньше сагровского.
    test "один уровень чужого класса возвращает базовый вариант", %{ruleset: ruleset} do
      pure = compute(ruleset, :half_elf, 41)
      mixed = Rules.compute(impure(:half_elf, 41), ruleset)

      assert pure.race_attack_bonus == 9
      assert mixed.race_attack_bonus == 6

      assert pure.racial_bonus.variant == :sagra_warrior
      assert mixed.racial_bonus.variant == :base

      # оба билда одной длины — сравниваются одинаковые лестницы, а не 40 с 41
      assert pure.character_level == mixed.character_level

      # 🔴 И ПОСЧИТАННЫЙ ВАРИАНТ БОЛЬШЕ НЕ ГЭП (задача 3.102, решение Dan
      # 25.08.2026): «посчитан вариант сагровика +9» — это ответ, а не дырка,
      # а весь список гэпов билда печатается под заголовком «ядро не смогло
      # посчитать N». Признание не выброшено, а переехало к самому числу
      # (`Summary.racial_bonus_note/2`), тем же предложением — оно проверяется
      # в `labels_test.exs` и в тестах обоих экранов.
      #
      # ⚠️ Тут проверяется ровно то, что раньше было гэпом, а стало тишиной:
      # без этой пары кейс зеленел бы и у правки, которая вырезала бы вариант
      # из записи ядра вовсе — а вариант и есть то, чем справка отличает
      # «посчитан базовый» от «посчитан вариант сагровика».
      assert racial_gaps(pure) == []
      assert racial_gaps(mixed) == []
    end

    # 🔴 **ЗДЕСЬ СТОЯЛ КЕЙС «на 39-м бонуса нет, но гэп называет причину» —
    # переписан 11.09.2026 (задача 3.181).** Ниже 40-го бонус не считался вовсе,
    # потому что функции роста не знал никто: «все числа приведены для 40-го
    # уровня», а таблицы нет ни на одной странице. Теперь она есть — не с вики
    # и не замером, а из разбора СЕРВЕРНЫХ СКРИПТОВ шарда, присланного
    # администрацией, — и решение Dan 11.09.2026 считать по нарастающей.
    #
    # ⚠️ Утверждение старого кейса не отменено, а сузилось до снапшота БЕЗ
    # таблицы: он обязан считать по-старому и говорить гэпом. Кейс на это стоит
    # ниже, и ruleset там СИНТЕТИЧЕСКИЙ.
    #
    # Ступени: 1–7 · 8–16 · 17–23 · 24–31 · 32–39 · 40+ (`sl_s_wp_inc.nss`).
    # Светлый эльф — исполнитель `attack`, единица = тир; билд набран воином,
    # то есть сагровик, значит `floor(тир × 3 / 2)`.
    test "бонус растёт ступенями по уровню персонажа", %{ruleset: ruleset} do
      # {уровень, сагровик, не-сагровик}
      table = [
        {1, 1, 1},
        {7, 1, 1},
        {8, 3, 2},
        {16, 3, 2},
        {17, 4, 3},
        {23, 4, 3},
        {24, 6, 4},
        {31, 6, 4},
        {32, 7, 5},
        {39, 7, 5},
        {40, 9, 6},
        {41, 9, 6}
      ]

      for {level, sagra, base} <- table do
        pure = compute(ruleset, :half_elf, level)
        mixed = Rules.compute(impure(:half_elf, level), ruleset)

        assert pure.race_attack_bonus == sagra, "сагровик, уровень #{level}"
        assert mixed.race_attack_bonus == base, "не сагровик, уровень #{level}"

        # и оговорки про уровень больше нет ни на одном: число известно везде
        assert racial_gaps(pure) == [], "уровень #{level}"
      end
    end

    # 🔴 Единственная точка ниже 40-го, которую ВИДЕЛИ В ИГРЕ — замер `AM1`
    # (Dan, 11.09.2026): светлый эльф **Варвар 17**, STR 14 / DEX 12, голым 19,
    # длинный меч +5 → **28**, праща +5 → **31**. Расовый терм +4 при любом
    # оружии, и ещё +4 сверху от дальнобойной группы, когда оружие расовое.
    #
    # ⚠️ Замер различал ТРИ чтения, а не подтверждал одно: «×2 раньше усечения»
    # дало бы 4 и 9, «округление вверх» — 5 и 10. Вышло 4 и 8, то есть усечение
    # вниз и × 3/2 раньше × 2.
    #
    # ⚠️ Варвар, а не воин: в `ClassNotRestrict` скриптов он входит наравне
    # с воином, и замер это подтвердил заодно — не будь множителя группы,
    # вышло бы 3 и 6.
    test "замер AM1: светлый эльф Варвар 17 — меч +4, праща +8", %{ruleset: ruleset} do
      abilities = %{@flat | str: 14, dex: 12}

      barbarian = fn weapon, feats ->
        %Build{} =
          build =
          Build.new(
            race: :half_elf,
            levels: List.duplicate(:barbarian, 17),
            base_abilities: abilities,
            gear: Gear.new(if(weapon, do: [weapon: weapon, feats: feats], else: []))
          )

        Rules.compute(build, ruleset)
      end

      naked = barbarian.(nil, [])
      sword = barbarian.(:longsword, [:siala_blade_proficiency])
      sling = barbarian.(:sling, [:siala_ranged_proficiency])

      # BAB варвара 17 + сила +2 — ровно 19 из листа, и расового терма нет:
      # бонус включает оружие в руках, а руки пусты.
      assert {naked.base_attack, naked.attack_bonus, naked.race_attack_bonus} == {17, 19, 0}

      # Меч — клинковое, дальнобойной группе не родня, и всё же расовый +4
      # появился: он даётся при ЛЮБОМ оружии.
      assert {sword.race_attack_bonus, sword.weapon_type_attack_bonus} == {4, 0}
      assert sword.attack_bonus == 23

      # Праща — расовая группа: два независимых терма по +4, вместе +8.
      # Ровно та сумма, которую движок даёт одним числом (`(3 × 3/2) × 2`).
      assert {sling.race_attack_bonus, sling.weapon_type_attack_bonus} == {4, 4}
      assert sling.attack_bonus == 26

      # ⚠️ В игре было 28 и 31 — разница ровно в +5 самого оружия, которых
      # этот билд не несёт: бонус даёт ТИП базового предмета, усиление
      # в механике не участвует.
      assert sling.attack_bonus - sword.attack_bonus == 3
    end

    # 🔴 Снапшот БЕЗ таблицы тиров считает как до 3.181 и говорит гэпом.
    # Умолчание направлено в сторону оговорки: данные, которые о росте молчат,
    # не имеют права молча начать его считать.
    #
    # ⚠️ Ruleset СИНТЕТИЧЕСКИЙ — таблица вынута вызовом, а не найдена живой
    # записью: живая запись назавтра получает данные, и контроль перестаёт
    # что-либо проверять (урок 3.85, пять контролей подряд).
    test "без таблицы тиров всё как до 3.181: гэп ниже 40-го", %{ruleset: ruleset} do
      without = put_in(ruleset.racial_bonuses.scaling, nil)

      stats = Rules.compute(build(:half_elf, 39), without)

      assert stats.race_attack_bonus == 0
      assert stats.attack_bonus == stats.base_attack
      assert {:missing_data, {:racial_bonus_level, :half_elf}} in stats.gaps

      at_40 = Rules.compute(build(:half_elf, 40), without)

      assert at_40.race_attack_bonus == 9
      assert racial_gaps(at_40) == []
    end

    # ⚠️ Положительный контроль к гэпу выше: раса, у которой бонуса нет вовсе,
    # не должна получать НИ ОДНОЙ оговорки про него — ни на 39-м, ни на 41-м.
    # Ложная тревога на пустом месте хуже отсутствующей: «у Гоблина мы что-то
    # не посчитали» неверно, у Гоблина нечего считать. Секция «Бонусы от расы»
    # у обеих рас состоит из одной фразы про шаманство (revid 16292).
    test "у расы без бонуса нет ни бонуса, ни гэпа", %{ruleset: ruleset} do
      for race <- [:halfling, :elf], level <- [1, 39, 40, 41] do
        stats = compute(ruleset, race, level)

        assert stats.racial_bonus == nil, "#{race} #{level}"
        assert stats.race_attack_bonus == 0, "#{race} #{level}"

        # ⚠️ Не «термов AC нет вовсе»: у Гоблина есть ванильный `Small stature`,
        # и он тут ни при чём. Проверяется отсутствие терма ОТ РАСЫ Сиалы.
        assert shard_race_ac_terms(stats) == [], "#{race} #{level}"

        assert racial_gaps(stats) == [], "#{race} #{level}: #{inspect(racial_gaps(stats))}"
      end
    end

    # Дельта на левелапе выводится из двух полных `compute`, отдельного
    # инкрементального пути нет (CLAUDE.md §5) — значит шаг ступени виден
    # в превью сам, без единой строчки про расу в дельте. ⚠️ Раньше здесь
    # проверялось появление бонуса из нуля на 40-м; теперь — ШАГ, и это то же
    # самое утверждение про механизм дельты.
    test "шаг ступени виден в дельте 39 → 40 сам", %{ruleset: ruleset} do
      build = build(:half_elf, 39)
      %{before: before, after: later} = Rules.preview_level_up(build, :fighter, ruleset)

      assert before.race_attack_bonus == 7
      assert later.race_attack_bonus == 9

      # +1 базовой атаки за 40-й уровень эпик не даёт (чётный), значит вся
      # разница в AB — это ровно расовый бонус.
      assert later.attack_bonus - before.attack_bonus == 2
    end

    test "vanilla не знает про расовый бонус вовсе", %{vanilla: vanilla} do
      assert vanilla.racial_bonuses == nil

      stats = compute(vanilla, :half_elf, 41)

      assert stats.racial_bonus == nil
      assert stats.race_attack_bonus == 0
      assert racial_gaps(stats) == []
    end
  end

  describe "кап атаки +20 — один потолок на все внутрикапные источники" do
    # ⚠️ Потолок здесь опускается искусственно, и это находка, а не удобство
    # теста: **при настоящем ruleset'е кап атаки +20 недостижим вовсе.** Всё,
    # что ядро умеет положить под него, — это +6 от вещей (кап прибавки
    # характеристики +12 даёт +6 к модификатору) и +9 от расы у сагровика, то
    # есть +15. Проверять «расовый бонус не пробивает потолок» на настоящих
    # числах нечем, и тест зеленел бы ни на чём.
    #
    # ⚠️ С задачи 1.12b источников под этим потолком ТРИ, а не два: третий —
    # собственные прибавки билда (`own_attack_bonus`). Здесь их нет намеренно
    # (`build/2` не берёт фитов), поэтому оба теста ниже остались про два
    # источника; про все три — `attack_bonuses_test.exs`. Максимум под капом
    # стал +16, и он по-прежнему меньше 20.
    #
    # 🔴 **А с 10.08.2026 (задача 3.22) внутрикапный источник у атаки остался
    # РОВНО ОДИН — расовый бонус Сиалы.** Dan назвал состав капа списком, и
    # модификатора силы в нём нет ни из какого источника, включая вещи
    # (`GAME_CHECKS.md` кейс J1) — значит `gear` вынесен наружу. Поэтому тест
    # ниже разделён надвое: на настоящих данных под капом режется только раса,
    # а инвариант «клип ОДИН на всё, что покрыто» проверяется на ruleset'е,
    # который возвращает вещи внутрь. Второе — не мёртвая ветка: ровно так
    # данные и выглядели до 10.08.2026, и ровно такой источник вернётся с
    # задачей 3.5 (прямой бонус атаки предмета).
    test "на настоящих сторонах режется только раса, вещи ложатся поверх", %{ruleset: ruleset} do
      tight = with_attack_cap(ruleset, 8)
      stats = Rules.compute(geared(build(:half_elf, 40), abilities: %{str: 12}), tight)

      # предпосылка: оба источника ненулевые и каждый сам по себе НИЖЕ потолка
      assert stats.gear_attack_bonus == 6
      assert stats.race_attack_bonus == 9

      # раса 9 → 8 (срезано 1), вещи +6 сверху: 14, а не 8 (кап на всё, как было
      # до 10.08.2026) и не 15 (кап не сработал вовсе).
      assert stats.attack_extra_bonus == 14
      assert stats.attack_cap_clipped == -1
      assert stats.attack_bonus == stats.base_attack + 14
      assert :attack_bonus in stats.capped
    end

