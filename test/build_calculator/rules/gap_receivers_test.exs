defmodule BuildCalculator.Rules.GapReceiversTest do
  @moduledoc """
  Который факт шарда считается гэпом — и в данных, и в конкретном билде.

  Задача 3.28, решение Dan 10.08.2026: гэп — дырка в нашем ОТВЕТЕ, а не в наших
  знаниях. Про урон, длительность, иммунитеты, призывы, яды, ловушки, скорость
  бега, фамильяра, кастомные предметы и баффы калькулятор не отвечает вовсе,
  значит и дырки в ответе про них нет.

  ⚠️ **Направление ошибки — в сторону ПОКАЗА, и на это здесь три отдельных
  теста**: факт без метки остаётся гэпом, рулсет без словаря не фильтрует
  ничего, и одного «нашего» получателя из нескольких достаточно. Молчаливо
  погашенный гэп неотличим от уверенного неверного ответа (CLAUDE.md §9), и
  именно этой ошибки механизм не имеет права делать сам.

  ⚠️ **Числа этой задачи двусмысленны дважды, поэтому каждое названо в имени
  теста.** Фактов в `siala_41/classes.json` 126, и гэпов у `siala_41` до фильтра
  было тоже 126 — совпадение: гэпы порождают только 89 фактов из 126, остальные
  37 гэпов не про классы вовсе. Дальше «фактов с нашим получателем» = 126 − 76 =
  50 и «гэпов после фильтра» = 126 − 76 = 50 равны из-за общего вычитаемого
  а не потому, что это одно число.

  ⚠️ **И второе совпадение устойчиво, а не разово:** оба числа равны `37 + N`,
  где 37 — применённых фактов и, отдельно от них, гэпов не про классы шарда,
  а N — гэпов про классы. Совпадают именно эти два 37. Поэтому правка данных
  10.08.2026 (`Rage`, `Bull's strength` и `Shadow Evade` ушли под баффы решением
  Dan) сдвинула оба числа с 56 на 53 **разом** — и это не признак того, что
  число одно. Замеры 13.08.2026 сдвинули их ещё раз, с 53 на 51: «Свет плута»
  и Набор для обезвреживания ловушек перестали быть нашими (`GAME_CHECKS.md`,
  кейс L1 — прибавка не идёт в значение навыка, и решением Dan предмет
  в конструкторе не упоминается вовсе), и ещё раз, с 51 на 50, кейсом L2b:
  загадочная фраза монаха про «базовый бонус атаки» оказалась про Flurry
  of blows, а Шквал активируемый — то есть бафф.
  """

  use ExUnit.Case, async: true

  alias BuildCalculator.Data
  alias BuildCalculator.Rules
  alias BuildCalculator.Rules.Build
  alias BuildCalculator.Rules.GapReceivers

  setup_all do
    %{siala: Data.ruleset!("siala_41"), vanilla: Data.ruleset!("vanilla")}
  end

  defp class_change_gaps(gaps) do
    for {:not_modelled, {:class_change, class, what}} <- gaps, do: {class, what}
  end

  defp feat_change_gaps(gaps) do
    for {:not_modelled, {:feat_change, feat, what}} <- gaps, do: {feat, what}
  end

  defp skill_change_gaps(gaps) do
    for {:not_modelled, {:skill_change, skill, what}} <- gaps, do: {skill, what}
  end

  defp fact(what, affects), do: %{"what" => what, "affects" => affects}

  # Рулсет с подменённым списком неприменённых фактов у одного класса. Синтетика,
  # а не правка `priv/` — вопрос «как код читает метку» решается формой факта,
  # а не составом файла шарда.
  defp with_facts(ruleset, class_id, facts),
    do: put_in(ruleset, [:classes, class_id, :siala_unapplied], facts)

  defp gaps_of(ruleset, class_id, levels \\ 5) do
    Build.new(levels: List.duplicate(class_id, levels))
    |> Rules.compute(ruleset)
    |> Map.fetch!(:gaps)
  end

  # ---------------------------------------------------------------- ours?/2 --

  describe "ours?/2 — таблица из moduledoc самого модуля" do
    test "получатель решает, а неясность решается в сторону показа" do
      our = MapSet.new(["hp"])

      assert GapReceivers.ours?(fact("x", ["hp"]), our)
      assert GapReceivers.ours?(fact("x", ["hp", "damage"]), our), "одного нашего достаточно"
      refute GapReceivers.ours?(fact("x", ["damage"]), our)
      assert GapReceivers.ours?(%{"what" => "x"}, our), "метки нет — значит гэп"
      assert GapReceivers.ours?(fact("x", []), our), "пустой список ничего не утверждает"
      assert GapReceivers.ours?(fact("x", ["damage"]), MapSet.new()), "нет словаря — нет фильтра"
    end

    test "filter/2 сохраняет порядок и не трогает ничего лишнего" do
      our = MapSet.new(["hp"])
      facts = [fact("a", ["hp"]), fact("b", ["damage"]), fact("c", ["damage", "hp"])]

      assert Enum.map(GapReceivers.filter(facts, our), & &1["what"]) == ~w(a c)
    end
  end

  # ---------------------------------------------------------- bonus_ours?/2 --

  describe "bonus_ours?/2 — то же правило для записи файла прибавок" do
    # Запись разметки проходит через загрузчик, поэтому ключи у неё атомы, а
    # получатели — как их пишет источник. Отличие ровно в одном ключе, значит и
    # ответы обязаны совпадать до последней строки таблицы.
    test "ответы совпадают с ours?/2 строка в строку" do
      our = MapSet.new(["hp"])

      assert GapReceivers.bonus_ours?(%{id: :x, affects: ["hp"]}, our)
      assert GapReceivers.bonus_ours?(%{id: :x, affects: ["hp", "damage"]}, our)
      refute GapReceivers.bonus_ours?(%{id: :x, affects: ["damage"]}, our)
      assert GapReceivers.bonus_ours?(%{id: :x, affects: nil}, our), "метки нет — значит гэп"
      assert GapReceivers.bonus_ours?(%{id: :x, affects: []}, our), "пустой список не утверждает"
      assert GapReceivers.bonus_ours?(%{id: :x, affects: ["damage"]}, MapSet.new()), "нет словаря"
    end

    # 🔴 Поля может не быть ВОВСЕ, и это не гипотеза: до 18.08.2026 так
    # выглядела каждая запись `feat_save_bonuses.json`, последнего из шести
    # файлов без разметки, а сегодня так выглядит любая запись
    # `feat_hp_bonuses.json` (у него `not_modelled`-записей нет вовсе — нечего
    # размечать) и синтетическая запись в тестах статов. `Map.get/2` вместо
    # `record.affects` — не перестраховка, а условие того, что фильтр не падает
    # на живых данных и ошибается в сторону показа.
    test "записи без поля вовсе — гэп, а не падение" do
      assert GapReceivers.bonus_ours?(%{id: :x, verdict: :not_modelled}, MapSet.new(["hp"]))
    end

    # Строковую форму она не читает — и ошибается при этом В СТОРОНУ ПОКАЗА:
    # чужая запись выглядит для неё неразмеченной, то есть остаётся гэпом.
    # Проверяется на факте, у которого ответы обязаны разойтись: подай сюда
    # сиальский факт по ошибке — получишь лишнюю оговорку, а не пропавшую.
    test "чужая форма записи читается как неразмеченная, а не как не наша" do
      our = MapSet.new(["hp"])

      refute GapReceivers.ours?(fact("x", ["damage"]), our)
      assert GapReceivers.bonus_ours?(fact("x", ["damage"]), our)
    end
  end

  # Третий адаптер над тем же правилом — задача 3.98. Он берёт ruleset целиком,
  # потому что переписать нельзя дважды именно САМ ПОИСК записи: два читателя
  # спрашивают про один фит с двух сторон (оговорка про прибавку и оговорка
  # про неназванное значение с вещи) и отвечали по-разному ровно потому, что
  # чтение словаря было приватной копией. Разошлись они в тот же день, когда
  # первого научили спрашивать (3.93), — приватной копии хватило одного захода.
  describe "feat_effect_ours?/2 — то же правило по id фита" do
    test "ответы совпадают с ours?/2 строка в строку" do
      rs = fn label ->
        %{
          gap_receivers: %{our: MapSet.new(["hp"]), not_our: MapSet.new(["damage"])},
          feat_effect_receivers: %{x: label}
        }
      end

      assert GapReceivers.feat_effect_ours?(:x, rs.(%{"affects" => ["hp"]}))
      assert GapReceivers.feat_effect_ours?(:x, rs.(%{"affects" => ["hp", "damage"]}))
      refute GapReceivers.feat_effect_ours?(:x, rs.(%{"affects" => ["damage"]}))
      assert GapReceivers.feat_effect_ours?(:x, rs.(%{"affects" => []})), "пустая метка"

      refute GapReceivers.feat_effect_ours?(
               :x,
               rs.(%{"affects" => ["hp"], "not_a_gap" => %{"who" => "фикстура"}})
             ),
             "решение владельца едет тем же вызовом"
    end

    # 🔴 Три способа не найти метку, и все три обязаны отвечать «гэп остаётся».
    # Третий — отсутствие СЛОВАРЯ целиком: ruleset без сиальского слоя живёт
    # именно так, и молчание там было бы худшим из исходов.
    test "нет записи, нет словаря, нет ключа — всё это гэп, а не тишина" do
      dictionary = %{
        gap_receivers: %{our: MapSet.new(["hp"]), not_our: MapSet.new(["damage"])},
        feat_effect_receivers: %{}
      }

      assert GapReceivers.feat_effect_ours?(:x, dictionary), "записи нет"

      assert GapReceivers.feat_effect_ours?(:x, %{
               gap_receivers: %{our: MapSet.new(), not_our: MapSet.new()},
               feat_effect_receivers: %{x: %{"affects" => ["damage"]}}
             }),
             "словаря получателей нет"

      assert GapReceivers.feat_effect_ours?(:x, %{}), "ключа feat_effect_receivers нет вовсе"
    end
  end

  # ⚠️ Сторож на маршрут, а не на разметку: поле обязано ДОЕЗЖАТЬ до ядра из
  # всех семи файлов прибавок. Ровно этого не было до 17.08.2026 — разметку
  # завели у пяти, а читал её один, и у четырёх файлов метка была материалом,
  # а не фильтром. Тест ловит повтор той же ошибки с другой стороны: файл,
  # чьи записи приходят БЕЗ ключа, разметить в данных можно, и она молча
  # не сработает.
  describe "поле affects доезжает до ядра из всех семи файлов прибавок" do
    @markups [
      :ac_bonuses,
      :ability_bonuses,
      :attack_bonuses,
      :hp_bonuses,
      :skill_bonuses,
      :save_bonuses,
      # Седьмой, задача 3.45. Размечать ему сегодня нечего (нет ни одной записи
      # `not_modelled`), и ровно поэтому он здесь: файл без разметки — это тот
      # случай, в котором маршрут ломается незаметно.
      :spell_resistance
    ]

    test "ключ есть у каждой записи каждого файла", %{siala: siala} do
      for markup <- @markups,
          half <- [:applied, :unmodelled, :counted_elsewhere],
          record <- get_in(siala, [markup, half]) || [] do
        assert Map.has_key?(record, :affects),
               "#{markup}/#{half}: запись #{record.id} не несёт ключа :affects"
      end
    end

    # ⚠️ И вторая половина, названная числом. Наполнено было ПЯТЬ файлов из
    # шести с 17.08.2026 до 18.08.2026 — у Ярости из-за этого оговорка про
    # сейвы оставалась, пока оговорки про AC и характеристику уже были сняты.
    # `feat_save_bonuses.json` (шестой) дошёл 18.08.2026, тем же полем и
    # правилом, без исключений: теперь наполнены все шесть, где вообще есть
    # что размечать.
    test "наполнены все пять файлов, где есть not_modelled-записи", %{siala: siala} do
      marked =
        for markup <- @markups,
            Enum.any?(get_in(siala, [markup, :unmodelled]) || [], &is_list(&1.affects)),
            do: markup

      assert Enum.sort(marked) == [
               :ability_bonuses,
               :ac_bonuses,
               :attack_bonuses,
               :save_bonuses,
               :skill_bonuses
             ]

      # `hp_bonuses` и `spell_resistance` не в списке по другой причине, и путать
      # её с остальными нельзя: у обоих нет ни одной записи `not_modelled` вовсе
      # (задачи 3.37 и 3.45), то есть размечать нечего, а не «забыли». У сейвов
      # теперь размечены все 21.
      assert siala.hp_bonuses.unmodelled == []
      assert siala.spell_resistance.unmodelled == []
      assert length(siala.save_bonuses.unmodelled) == 21
      assert Enum.all?(siala.save_bonuses.unmodelled, &is_list(&1.affects))
    end
  end

  # ----------------------------------------------------------- held_ours?/2 --

  describe "held_ours?/2 — то же для фита, которого никто не БРАЛ" do
    # Фит с вещи персонаж держит, но не получал: пререквизиты у него не
    # проверяются, слот не тратится, класс его не выдавал. Значит факт, который
    # «наш» ТОЛЬКО потому, что он про доступность фита, этому персонажу не
    # говорит ничего — а всё остальное говорит ровно то же, что и взявшему
    # слотом, потому что эффект фита с вещи считается (Dan, 09.08.2026).
    @our MapSet.new(["hp", "feat_availability"])

    test "снимается ровно один получатель, и только когда он единственный наш" do
      refute GapReceivers.held_ours?(fact("x", ["feat_availability"]), @our)

      assert GapReceivers.held_ours?(fact("x", ["feat_availability", "hp"]), @our),
             "одного НЕ-про-доступность получателя достаточно"

      refute GapReceivers.held_ours?(fact("x", ["feat_availability", "damage"]), @our),
             "остаток не наш — значит и спасти факт ему нечем"

      assert GapReceivers.held_ours?(fact("x", ["hp"]), @our)
      refute GapReceivers.held_ours?(fact("x", ["damage"]), @our)
    end

    test "неясность по-прежнему решается в сторону показа" do
      assert GapReceivers.held_ours?(%{"what" => "x"}, @our), "метки нет — значит гэп"
      assert GapReceivers.held_ours?(fact("x", []), @our), "пустой список ничего не утверждает"

      assert GapReceivers.held_ours?(fact("x", ["feat_availability"]), MapSet.new()),
             "нет словаря — нет фильтра"
    end

    # ⚠️ Ловушка композиции, ради которой это выражено предикатом, а не
    # вычитанием множеств: у `ours?/2` ПУСТОЙ `our` означает «фильтра нет вовсе».
    # Словарь из одной только доступности, из которого её вычли, стал бы пустым —
    # и фильтр не выключил бы ничего, а показал БЫ ВСЁ, ровно наоборот.
    test "словарь из одной доступности не превращается в «показать всё»" do
      only = MapSet.new(["feat_availability"])

      refute GapReceivers.held_ours?(fact("x", ["feat_availability"]), only)
      refute GapReceivers.held_ours?(fact("x", ["damage"]), only)
      assert GapReceivers.held_ours?(%{"what" => "x"}, only), "метки нет — по-прежнему гэп"
    end

    test "filter_held/2 сохраняет порядок" do
      facts = [fact("a", ["hp"]), fact("b", ["feat_availability"]), fact("c", ["hp"])]

      assert Enum.map(GapReceivers.filter_held(facts, @our), & &1["what"]) == ~w(a c)
    end

    # Имя получателя — единственное, которое ядро называет по буквам. Если
    # data-miner его переименует, фильтр тихо расширится обратно, а не сломается;
    # поэтому сторож здесь.
    test "получатель, который снимается, в словаре данных существует", %{siala: siala} do
      assert MapSet.subset?(
               GapReceivers.about_acquiring_a_feat(),
               GapReceivers.vocabulary(siala).our
             )
    end
  end

  # ------------------------------------------------------- словарь рулсетов --

  describe "словарь приходит из данных" do
    test "у siala_41 он закрыт и разведён на два множества", %{siala: siala} do
      vocabulary = GapReceivers.vocabulary(siala)

      # ⚠️ 21 → 22 (17.08.2026, задача про Мастера оружия): пришёл `counted_elsewhere` —
      # факт про НАШ получатель, но применённый ДРУГОЙ записью данных
      # (vanilla/feat_attack_bonuses.json), поэтому этот not_our не о теме,
      # которую калькулятор не считает, а о записи, которая ничего не прибавляет
      # к уже посчитанному.
      #
      # ⚠️ 22 → 26 (25.08.2026, задача 3.93): `save_dc`, `metamagic`,
      # `critical_hit`, `concealment` — четыре механики, которых калькулятор
      # не считает и про которые повторяемые фиты до того дня говорили
      # «прибавку в статы не считаем». Словарь сам это разрешает («расширяется
      # по факту, а не заранее»), а растянуть вместо этого соседнее имя было бы
      # разметкой по догадке: маскировка — не резист, ДЦ чужого броска — не наш
      # сейв, крит-диапазон — не урон.
      assert MapSet.size(vocabulary.our) == 15
      assert MapSet.size(vocabulary.not_our) == 26
      assert MapSet.disjoint?(vocabulary.our, vocabulary.not_our)
      assert "hp" in vocabulary.our
      assert "damage" in vocabulary.not_our
    end

    # ⚠️ Пустой словарь — не ошибка: у ванили нет слоя шарда вовсе, и фильтр
    # обязан быть выключен, а не резать всё под ноль.
    test "у vanilla он пуст, и это выключает фильтр, а не включает его наглухо",
         %{vanilla: vanilla} do
      assert GapReceivers.our(vanilla) == MapSet.new()
      assert GapReceivers.ours?(fact("x", ["damage"]), GapReceivers.our(vanilla))
    end

    test "рулсет без поля вовсе читается как рулсет без словаря" do
      assert GapReceivers.vocabulary(%{}) == %{our: MapSet.new(), not_our: MapSet.new()}
      assert GapReceivers.ours?(fact("x", ["damage"]), GapReceivers.our(%{}))
    end
  end

  # ------------------------------------------------------ гэпы данных, 126 → 48 --

  describe "список гэпов ДАННЫХ (ruleset.gaps)" do
    # ⚠️ 47 → 48 (14.08.2026): слой фитов начал доезжать до этого списка, и
    # прибавил ровно ОДИН гэп — `improved_evasion / siala_note`. Разметка
    # `affects` у фитов появилась в тот же день; без неё та же строка кода
    # добавила бы сюда 21 гэп, из которых 20 про урон, длительность и
    # иммунитеты, то есть ровно то, что задача 3.28 отсюда убрала.
    #
    # ⚠️ 48 → 52 (14.08.2026, тем же днём, третьим слоем): навыки получили
    # `affects` у всех 53 фактов (не только у неприменённых, как у фитов — у
    # записи навыка, как и у класса, нет своего машинного `type`/`use`, значит
    # классифицировать некого освободить), и прибавили ЧЕТЫРЕ гэпа:
    # `craft_trap / class_skills` (тогда это читалось как расхождение
    # с classes.json — какой навык шард добавил Теневому танцору, set_trap там
    # или craft_trap здесь; ⚠️ 17.08.2026 замер показал, что верны оба, см. ниже),
    # `set_trap / class_skills_unchanged`, и по разу `listen` / `spot` —
    # `rogue_stealth_penalty`, штраф вора в скрытности со стороны навыка,
    # парный `{:class_change, :rogue, "stealth_perception_penalty"}` тут же
    # рядом (задача "навыки: получатели у фактов", data-miner).
    # ⚠️ 52 → 51 (15.08.2026, задача 3.31): ушёл `{:not_modelled,
    # {:caster_advancement, :epic_spell_access}}` — оговорка «настоящее
    # требование шести эпических заклинаний другое, и посчитать его нечем».
