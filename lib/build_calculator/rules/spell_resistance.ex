defmodule BuildCalculator.Rules.SpellResistance do
  @moduledoc """
  Сопротивление заклинаниям (SR) — сколько его у персонажа и из чего оно собрано.

  До задачи 3.45 ядро не считало SR вовсе: билд «Мастер Монах» (монах 35 плюс
  девять взятий `Improved spell resistance`) нёс на этом месте оговорку
  `{:not_modelled, {:feat_bonus, :improved_spell_resistance}}`, а страница вики
  печатала **63**. Обе формулы при этом лежали у нас в репозитории с первого
  парсинга — прозой в `description` фитов. **Проза в файле данных правилом
  не является, пока её кто-нибудь не читает**; это четвёртый случай той же формы
  после `Zen archery`, активации расового бонуса и базы характеристик
  для требований.

  ## Здесь нет ни одного фита по имени

  Кто даёт SR, сколько и в какой форме — данные,
  `priv/rules/vanilla/feat_spell_resistance.json`, читает
  `BuildCalculator.Data.Loader`. Ни `diamond_soul`, ни `monk` в этом файле нет
  и быть не должно.

  ## Две формы величины, и почему они не одна

    * **уровень класса плюс число** — `Diamond soul`: «spell resistance equal to
      their class level + 10». ⚠ Формула, а не таблица, и это выбор данных:
      у соседей (`Rules.ArmorClass`, `Rules.SaveBonuses`) ступени лежат таблицей
      потому, что таблицей это напечатано на странице класса, а у монаха колонки
      SR в таблице прогрессии нет вовсе — есть одно предложение. Разбор
      в `_amount_kinds` файла.
    * **за взятие, с потолком эффекта** — `Improved spell resistance`: +2 за
      каждое, «to a maximum of +20». Та же форма, что у `Epic toughness`
      в `Rules.FeatBonuses`, и считается так же — `Build.feat_takes_owned/4`,
      то есть слоты **плюс** объявленный с вещи фит (Dan, 09.08.2026).

  ## Два потолка, и путать их нельзя

  `max_total` — потолок **эффекта**, со страницы фита. Потолок **числа взятий**
  (10) живёт отдельно, в `siala_41/feats.json` → `repeatable.max_takes`, и его
  проверяет `Rules.FeatChoices`. Совпадение арифметики (10 × 2 = 20) —
  совпадение, а не одно число, записанное дважды: потолок взятий считает только
  слоты (замер H8, 14.08.2026), потолок эффекта — оба источника. Девять слотов
  плюс объявленный с вещи фит дают десять взятий и +20; десять слотов плюс
  вещь — одиннадцать взятий и всё те же +20.

  ⚠ **Ограничителя на итог нет никакого**, и 71 — не потолок, а арифметика:
  монах 41 (+10) плюс десять взятий (+20). Fandom пишет «maximum possible spell
  resistance of 70» — то же сложение на ванильном капе 40, и «починить» 71 на 70
  по этой фразе было бы ошибкой (решение Dan, 18.08.2026).

  ## Складывается не всё

  Общее правило источника — «spell resistance does not stack»: из разных
  источников засчитывается **наибольший**. Два наших слагаемых складываются
  потому, что вторая страница говорит это дословно («This feat stacks with
  *diamond soul*»), а не по аналогии. Отсюда `total/1` — сумма, и отсюда же
  оговорка про предметы: SR с вещи не прибавился бы, а **конкурировал**, и
  на нижних уровнях выдачи выигрывал бы (крафт Сиалы доходит до 28 СР при нашем
  22 у монаха 12). См. `gaps/4` и `_gear_decision` в файле данных.

  ## Ноль — это ответ, а не «не знаю»

  У билда без обоих фитов `total/1` даёт **0**, а не `nil`, и термов нет вовсе.
  Разведка по девяти файлам корпуса сплошная: SR дают ровно два фита, ни один
  класс, навык или раса — ни одного, то есть ноль здесь полон, а не приблизителен.
  `nil` в этом ядре означает «честно посчитать нельзя» и кладёт причину в `gaps`;
  сказать так про пустоту, которую мы знаем целиком, значило бы завести дырку
  на месте ответа.

  ⚠ **Показывать ли строку — вопрос интерфейса, и решён он не здесь** (Dan,
  18.08.2026: «Чисто SR выводим для билдов с 12+ уровнями монаха»). Ядро отдаёт
  и число, и термы; веб-слой волен смотреть на уровни монаха или на пустой
  список термов. Ворота эти совпадают везде, кроме одного случая — фита,
  объявленного с вещи, — и различать их поэтому обязан тот, кто печатает.
  """

  alias BuildCalculator.Rules.{Bonuses, Build}

  @markup :spell_resistance

  @typedoc """
  Вклад одного источника в сопротивление заклинаниям.

    * `id` — фит (сегодня только он), для разбора и для гэпов
    * `source` — `{:feat, id}` / `{:class, id}` / `{:skill, id}` /
      `{:race_feat, id}`
    * `spell_resistance` — величина, уже посчитанная для этого билда
    * `takes` — сколько взятий за ней стоит (`1` у неповторяемого)
    * `capped?` — потолок эффекта, названный страницей самого фита, сработал.
      ⚠ Не `ruleset.stat_caps`: потолка на SR не объявляет ни один ruleset,
      поэтому этот флаг **не** попадает в `DerivedStats.capped` — там значится
      «упёрлось в потолок из `stat_caps`», а величины у такого потолка здесь нет
  """
  @type term_entry :: %{
          id: atom(),
          source: {atom(), atom()},
          spell_resistance: integer(),
          takes: pos_integer(),
          capped?: boolean()
        }

  @doc """
  Слагаемые сопротивления заклинаниям этого билда, в порядке самих данных.

  Только записи с вердиктом `applied`; источник, который персонаж не держит,
  терма не даёт. Ноль тоже не даёт: `Improved spell resistance` без единого
  взятия — это не строка «+0» в разборе.

  ⚠ `level` не украшение: дельта считается как разность двух полных `compute`
  по обрезанным билдам, поэтому «держит ли» и «сколько взятий» — всегда вопрос
  про **тот** уровень.
  """
  @spec terms(Build.t(), map(), non_neg_integer()) :: [term_entry()]
  def terms(%Build{} = build, ruleset, level) do
    for record <- Bonuses.held(build, ruleset, @markup, level),
        term = term(record, build, ruleset, level),
        term.spell_resistance != 0 do
      term
    end
  end

  @doc """
  Те же слагаемые одним числом.

  Сумма, а не максимум, и это прочитано, а не выведено: общее правило источника —
  «spell resistance does not stack», но `Improved spell resistance` объявляет своё
  сложение с `Diamond soul` отдельным предложением. Сложить их по аналогии,
  без этой строки, было бы ровно тем приёмом, на котором дважды сломались потолки
  сейвов и атаки.
  """
  @spec total([term_entry()]) :: integer()
  def total(terms), do: Bonuses.sum(terms, :spell_resistance)

  # ⚠ Две ветки и никакого catch-all, сознательно. Какие формы величины вообще
  # могут дойти до `applied`-записи, проверяет загрузчик
  # (`@applied_spell_resistance_kinds`, падает на **компиляции**), поэтому
  # несовпавшая форма — это сломанная сборка, а не живой запрос. Ветка-заглушка
  # с нулём превратила бы это в ровно ту поломку, ради которой вся разметка
  # и заведена: прибавку, которая молча не считается.

  # `Diamond soul`: уровень монаха + 10. Источник называет и случай без уровней
  # класса вовсе — «any character without monk levels will only gain spell
  # resistance 10», — то есть формула та же и при нуле, и отдельного правила
  # под объявленный с вещи фит не нужно.
  defp term(
         %{id: id, amount: %{kind: :class_level_plus, class: class, plus: plus}},
         build,
         _ruleset,
         level
       ) do
    reached = Bonuses.class_level(build, class, level)

    %{
      id: id,
      source: {:feat, id},
      spell_resistance: reached + plus,
      takes: 1,
      capped?: false
    }
  end

  # `Improved spell resistance`: +2 за взятие с потолком эффекта на сумме.
  #
  # ⚠ Матчится по `source: {:feat, id}`, а не по одному id, и это сторож, а не
  # педантизм: взятия — свойство **фита**, и запись этой формы, ключёванная
  # таблицей класса или расовой склонностью, взятий бы не имела —
  # `feat_takes_owned/4` ответил бы нулём, а `max(…, 1)` превратил бы ноль
  # в правдоподобное одно взятие. Такой записи нет; несовпавшая ветка — то,
  # чем это удерживается.
  #
  # ⚠ `max(…, 1)` — ровно для одного случая: фит, которым персонаж **владеет**,
  # но за которым нет ни слота, ни вещи, то есть выданный классом. Сегодня SR
  # за взятие не выдаёт ни один класс, так что это сторож, а не живое правило;
  # без него такой фит был бы во владении и не стоил бы ничего.
  defp term(
         %{source: {:feat, id}, amount: %{kind: :per_take, sr: sr, max_total: max_total}},
         build,
         ruleset,
         level
       ) do
    takes = max(Build.feat_takes_owned(build, ruleset, id, level), 1)
    total = takes * sr

    %{
      id: id,
      source: {:feat, id},
      spell_resistance: min(total, max_total),
      takes: takes,
      capped?: total > max_total
    }
  end

  @doc """
  Источники SR, которые этот билд держит, а модель их не считает.

  Идентификаторы, по порядку данных. Билд превращает их в
  `{:not_modelled, {:spell_resistance, id}}`.

  ⚠ **Сегодня эта функция не возвращает ничего ни на одном билде**, и это
  проверенный факт, а не догадка: в `vanilla/feat_spell_resistance.json` нет
  ни одной записи с вердиктом `not_modelled` — сплошная разведка нашла ровно
  два источника SR, и оба посчитаны. Механизм при этом жив и нужен: новая запись
  с этим вердиктом включит его обратно, и тест проверяет обе стороны
  на подменённой разметке.
  """
  @spec unmodelled(Build.t(), map(), non_neg_integer()) :: [atom()]
  def unmodelled(%Build{} = build, ruleset, level) do
    Bonuses.rejected_ids(build, ruleset, @markup, level)
  end

  @doc """
  Гэпы этого стата: непосчитанные источники плюс оговорка про предметы.

  Форма живёт здесь, а не в `Rules.compute/2`: словарь стата принадлежит стату.

  ## Оговорка про предметы — решение, а не умолчание

  SR с вещей мы не считаем: поля под него нет и не будет (решение Dan,
  18.08.2026, «SR с вещи добавлять не надо»). Но **сказать об этом обязаны**,
  и здесь это дороже, чем у остальных статов, потому что вещь меняет не полноту
  ответа, а сам ответ: SR из разных источников **не складывается**, засчитывается
  наибольший. Крафт Сиалы (`siala:Крафт`, revid 20450) даёт пять ступеней вплоть
  до «28 СР», а наше число начинается с 22 (монах 12 + 10) — то есть до монаха 17
  включительно предмет наше число **перебивает**, и в игре у персонажа стоит 28
  там, где мы печатаем 22–27. Оговорка называет правило, а не отсутствующую
  величину: посчитать «максимум из двух» без второго числа всё равно нельзя,
  а правило игрок из остальной панели не выведет — везде, кроме SR, вещь
  прибавляет.

  ⚠ Только там, где мы печатаем число: у билда без SR оговорки нет. Оговорка
  про вопрос, который не возникает, — шум (тот же критерий, что
  у `Bonuses.cap_side_gaps/5`).

  ⚠ `terms` приходит аргументом, а не считается заново, чтобы «печатаем ли мы
  число» и «оговариваем ли мы его» не могли разойтись: это буквально один
  список.
  """
  @spec gaps(Build.t(), map(), non_neg_integer(), [term_entry()]) :: [tuple()]
  def gaps(%Build{} = build, ruleset, level, terms) do
    from_records =
      Bonuses.gaps(build, ruleset, @markup, level, &{:not_modelled, {:spell_resistance, &1}})

    from_records ++ if terms == [], do: [], else: [{:not_modelled, :spell_resistance_from_gear}]
  end

  @doc """
  Посчитана ли **вся** прибавка этого фита — тот же контракт, что
  у `Rules.FeatBonuses.whole_effect_counted?/2` и двух её сестёр.

  Утверждение — данных (`effect_coverage: "whole_feat"`), и никогда не выводится
  из того, что прибавка применена.

  Спрашивает это `Rules.FeatChoices.gaps/3` про повторяемый фит, и здесь такой
  ровно один — `Improved spell resistance`. До задачи 3.45 у каждого монашеского
  билда рядом с его SR висело «прибавку от фита в статы не считаем»; оговорка,
  спорящая с числом на экране, хуже отсутствующей.
  """
  @spec whole_effect_counted?(atom(), map()) :: boolean()
  def whole_effect_counted?(feat_id, ruleset) do
    Bonuses.whole_effect_counted?(ruleset, @markup, feat_id)
  end
end
