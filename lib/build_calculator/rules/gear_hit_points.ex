defmodule BuildCalculator.Rules.GearHitPoints do
  @moduledoc """
  Процент к максимуму HP за надетое: мини-сеты, крафтовые (именные)
  и уникальные вещи (задача 3.186).

  Третья часть системы мини-сетов, и единственная, у которой **свой второй
  вход**:

      Cgear  — крафтовые (именные) и уникальные вещи (`Gear.named_items`)
      Nmini  — сколько кусков комплектов идёт в счёт (`Rules.MiniSets.pieces/2`)
      Ctotal = Cgear + Nmini

      HPbonus = div(Hbase · (100 + P(Ctotal)), 100) − Hbase

  `P` — нелинейная таблица из данных (`ruleset.gear_hit_points`), от +15 % за
  одну вещь до +105 % за десять. Ни одного числа здесь нет: таблица, потолок
  слотов именных вещей и значение за её верхней границей приходят из ruleset'а.

  ## 🔴 На одиннадцатой вещи прибавка ОБРЫВАЕТСЯ В НОЛЬ

  «Counts 0 and above 10 select 0%» — так написан `switch` в `sl_s_maxhp_inc.nss`,
  и это не опечатка источника. При базе 400 HP десять вещей дают **+420**,
  одиннадцать — **+0**. Самая дорогая ловушка всей системы, поэтому у терма есть
  свой флаг `cut_off?`: интерфейс обязан уметь закричать об этом **до** того,
  как игрок соберёт такой билд, а не показать молчаливое падение числа.

  ## Целочисленная арифметика, а не умножение на дробь

  `div(Hbase · (100 + P), 100) − Hbase` — ровно то усечение, которым считает
  NWScript. `Hbase · 1.21` с округлением дало бы другое число на всякой базе,
  не делящейся на сто: `div(401 · 121, 100) = 485`, то есть **+84**, а не +84.21
  и не +85.

  ## ✅ `Hbase` — наше HP целиком, и это ИЗМЕРЕНО (замер `AP1`, 12.09.2026)

  Источник говорит «let `Hbase` be the value returned by `GetMaxHitPoints(oPC)`»
  — то есть максимум персонажа без самой этой прибавки: кости, телосложение
  (итоговое, с вещами) и фиты. Мы берём за `Hbase` всё, что считает
  `Rules.Progression.hit_points/3`, **включая «Дух Сиалы» +20**, и чем именно
  шард выдаёт эти двадцать очков, разбор не говорит вовсе.

  ⚠ **Здесь стояло «НАЗВАННОЕ допущение» — снято замером, а не решением.** Dan
  12.09.2026: «надел 2 минисета, получил 42 HP». У варвара 1-го уровня с
  телосложением 14 это `floor(35 · 121 / 100)`, где 35 — база **с** Духом;
  без Духа в базе вышло бы 38. Арифметика расчёта не сдвинулась ни на очко,
  сменился статус.

  ## ✅ Как куски превращаются в номер ячейки — тоже измерено

  **Номер ячейки = `Ctotal`**, то есть два куска одного набора дают +21 %,
  а не +15 %. Это было чтением скрипта против страницы «Мини Сэты», которая
  в одном предложении говорит и «2 вещи маленького сета дают 1 бонус, 3 вещи -
  2 бонуса» (дало бы `Nmini` минус число групп), и тут же «2 вещи (сет А) +
  2 вещи (сет Б) дают бонус 4 вещи». Тот же замер `AP1` убил первое чтение:
  42, а не 40.

  ⚠ **Второй замер того же дня (`AS1`) проверил второй вход и ещё две ячейки.**
  Волшебник 10 / Бледный призыватель 30 в четырёх состояниях — 813, 1050, 922
  и 867 HP, — и наши числа совпали со всеми четырьмя. Из них важнее прочих
  третье: тот же `Ctotal` = 4, набранный двумя крафтовыми вещами и двумя
  кусками вместо четырёх крафтовых, даёт тот же процент, то есть **крафтовая
  вещь и кусок в счёте взаимозаменяемы**.

  ⚠ **Измерены четыре ячейки из одиннадцати — 2, 3, 4 и 6.** Верхние (5, 7–10)
  и ОБРЫВ на одиннадцатой вещи по-прежнему держатся на одном чтении `switch`,
  и это ровно та часть таблицы, где ошибка стоила бы дороже всего. Полный
  разбор и все цитаты — в данных, `hp_percent_by_item_count`.

  ⚠ **Артефактные сеты к HP не ведут вовсе** — у них свой счётчик движка
  (`ArtSet_<class>`), и «Artifact membership alone is not read by the mini-set
  counter or HP formula». Слово Dan тем же днём: «Перчатки Мокси это сет,
  а не мини сет и он не даёт прибавку к здоровью, а вот крафт — даёт».

  ## Чего эта система стоит, а мы не считаем — решением, а не молчанием

  Верхом прибавка делится пополам (`riding_factor` 0.5), а раненому не
  применяется вовсе. Оба — **состояния боя, а не свойства билда**, и линия
  здесь та же, что у баффов (решение Dan 10.08.2026: «постоянное свойство
  персонажа — наше; то, что включается и кончается, — нет»). Гэпа на них нет
  и не должно быть: боевое состояние калькулятор не отвечает вовсе, а гэп —
  дырка в нашем ОТВЕТЕ, а не в знаниях (CLAUDE.md §9).
  """

  alias BuildCalculator.Rules.{Build, MiniSets}

  @typedoc """
  Что надетое добавило к HP — терм разбора (`hp_breakdown.gear_bonus`).

    * `pieces` / `named` — два входа по отдельности, `named` уже после клипа
      потолком слотов: разбор обязан уметь назвать, откуда взялся счёт
    * `count` — `Ctotal`, то самое число, по которому выбирается строка таблицы
    * `percent` — выбранная строка, `0` за её верхней границей
    * `amount` — сама прибавка, целочисленно
    * `cut_off?` — счёт ушёл ЗА таблицу, и прибавки нет вовсе: `percent` и
      `amount` нули по той же причине, что у пустого билда, и без этого флага
      две совершенно разные ситуации были бы неотличимы
  """
  @type term_entry :: %{
          pieces: non_neg_integer(),
          named: non_neg_integer(),
          count: non_neg_integer(),
          percent: non_neg_integer(),
          amount: integer(),
          cut_off?: boolean()
        }

  @doc """
  Терм прибавки к HP для этого билда — `nil`, когда прибавлять не за что.

  `nil` в трёх случаях, и они значат разное только для оговорок:
  правила у ruleset'а нет вовсе (ваниль), считать не от чего (`base` — `nil`,
  то есть HP билда посчитать не удалось) или `Ctotal` — ноль. Во всех трёх
  число HP остаётся ровно тем, чем было до задачи, — «билд без мини-сетов
  и именных вещей не сдвинулся ни на единицу» стоит отдельным тестом.

  ⚠ `base` приходит аргументом, а не считается здесь: `Hbase` — это результат
  `Rules.Progression.hit_points/3` со всеми его правилами (пол в 1 HP на
  уровень, растущий хит-дайс, «Дух Сиалы»), и второй его расчёт был бы вторым
  местом, где живёт формула HP.
  """
  @spec term(Build.t(), map(), non_neg_integer() | nil) :: term_entry() | nil
  def term(_build, _ruleset, nil), do: nil

  def term(%Build{} = build, ruleset, base) when is_integer(base) do
    case rule(ruleset) do
      nil ->
        nil

      %{percent: table, above_max: above, max_count: max_count} = rule ->
        pieces = MiniSets.pieces(build, ruleset)
        named = named_items(build, rule)
        count = pieces + named
        percent = Map.get(table, count, above)

        if count == 0 do
          nil
        else
          %{
            pieces: pieces,
            named: named,
            count: count,
            percent: percent,
            # ⚠ Сотня здесь — ЕДИНИЦА ИЗМЕРЕНИЯ таблицы («процент»), а не число
            # шарда: сама таблица, потолок слотов и значение за её верхней
            # границей приходят из данных. Игровое число, записанное литералом,
            # выглядело бы ровно так же, поэтому разница названа.
            amount: div(base * (100 + percent), 100) - base,
            cut_off?: count > max_count
          }
        end
    end
  end

  @doc """
  Сколько прибавка стоит этому билду — `0`, когда терма нет.

  Отдельно от `term/3`, потому что читателей у числа больше, чем у разбора:
  `Rules.compute/2` складывает его с `hp`, а разбор печатает только интерфейс.
  """
  @spec amount(term_entry() | nil) :: integer()
  def amount(%{amount: amount}), do: amount
  def amount(nil), do: 0

  @doc """
  Сколько крафтовых (именных) и уникальных вещей персонаж может носить вообще
  — число слотов из данных. `nil`, если правила у ruleset'а нет.

  Отдаётся геттером ровно по той же причине, что `Rules.MiniSets.slots/1`:
  строка «больше десяти не носят» обязана назвать число, а игровых чисел
  веб-слой не выдумывает (CLAUDE.md §5).

  ⚠ Это НЕ запрет вводить больше: расшаренная ссылка может нести что угодно
  и обязана открываться, а ввод сверх потолка — повод предупредить, а не
  отказать. Клип живёт здесь, в расчёте.

  ⚠ И это НЕ тот же потолок, которым клипается `Nmini`: у кусков слотов
  одиннадцать (правая рука считается), у именных вещей десять (счёт правой
  руки в скрипте закомментирован). Два числа, два слова источника.
  """
  @spec named_item_slots(map()) :: pos_integer() | nil
  def named_item_slots(ruleset) do
    case rule(ruleset) do
      %{named_item_slots: slots} -> slots
      nil -> nil
    end
  end

  @doc """
  На каком счёте прибавка обрывается в ноль — первое число ЗА таблицей.
  `nil`, если правила у ruleset'а нет.

  🔴 Заведено ради предупреждения в интерфейсе, и потому отдаётся числом,
  а не флагом на билде: игрок, у которого девять вещей, обязан узнать про
  обрыв **раньше**, чем соберёт одиннадцатую, — а билд с одиннадцатью уже
  ничего не прибавляет и сказать об этом задним числом поздно.
  """
  @spec cut_off_at(map()) :: pos_integer() | nil
  def cut_off_at(ruleset) do
    case rule(ruleset) do
      %{max_count: max_count} -> max_count + 1
      nil -> nil
    end
  end

  @doc """
  Чего этот билд не говорит за себя про HP от надетого.

    * `{:missing_data, :mini_set_hp_table}` — вещи заявлены, снапшот **знает
      про систему шарда**, а таблицы процентов у него нет: прибавку считать
      нечем, и HP меньше игрового — в пределе вдвое. Умолчание направлено
      в сторону оговорки, ровно как у правила счёта кусков.

  🔴 **Ванильному ruleset'у не достаётся ни одной, и это не пропуск** — той же
  линией, что у `Rules.MiniSets.gaps/2`: ни мини-сетов, ни именных вещей шарда
  в NWN нет вовсе, поэтому заявленные там вещи не значат ничего и оговаривать
  нечего. Разница между «системы нет» и «система есть, а таблицы нет» читается
  по `shard_bonus_scaling`.

  ⚠ **Формы `{:not_modelled, …}` здесь нет и быть не может.** До этой задачи
  билд с кусками говорил `{:not_modelled, :mini_set_hp_bonus}` — «в игре это
  двигает HP, а мы не считаем». Теперь считаем, и оставить признание значило бы
  пугать игрока тем, что уже сосчитано (CLAUDE.md §6, «ложная неопределённость
  наоборот»). Признание снято не вычёркиванием, а тем, что вернёт его само:
  снапшот без таблицы получает `missing_data` и прибавки не даёт.
  """
  @spec gaps(Build.t(), map()) :: [tuple()]
  def gaps(%Build{} = build, ruleset) do
    cond do
      not shard_system?(ruleset) -> []
      not is_nil(rule(ruleset)) -> []
      declared(build, ruleset) > 0 -> [{:missing_data, :mini_set_hp_table}]
      true -> []
    end
  end

  # ------------------------------------------------------------------ private --

  # Знает ли снапшот про систему шарда вовсе. Тот же вопрос и тот же признак,
  # что у `Rules.MiniSets`: у ванили ни мини-сетов, ни именных вещей нет,
  # и оговаривать там нечего.
  defp shard_system?(ruleset), do: is_map(Map.get(ruleset, :shard_bonus_scaling))

  defp rule(ruleset) do
    case Map.get(ruleset, :gear_hit_points) do
      %{} = rule -> rule
      _absent -> nil
    end
  end

  # Сколько вещей заявлено В ПРИНЦИПЕ — для оговорки, а не для счёта: у снапшота
  # без таблицы потолка слотов нет, а спросить «игрок что-то ввёл?» надо всё
  # равно. Куски считаются своим правилом, потому что одинокий кусок не значит
  # ничего и оговорки не заслуживает.
  defp declared(%Build{gear: gear} = build, ruleset),
    do: gear.named_items + MiniSets.pieces(build, ruleset)

  defp named_items(%Build{gear: gear}, %{named_item_slots: slots}),
    do: gear.named_items |> max(0) |> min(slots)
end
