  describe "виды бонуса, которым не во что лечь" do
    # 🔴 **ЗДЕСЬ ПРОВЕРЯЛОСЬ ОБРАТНОЕ до 16.08.2026** — что Гном и Могучий человек
    # получают `{:not_modelled, {:racial_bonus, race, kind}}` на любом уровне.
    # Решение Dan (задача 3.38): «если речь о поглотах, то мы просто ничего
    # не пишем. Потом если захотим добавить поглоты — добавим все условия, а пока
    # мы это не показываем, оговорку игнорируем, не показываем лишней информации».
    #
    # Это правило CLAUDE.md §9: **гэп — дырка в нашем ОТВЕТЕ, а не в наших
    # знаниях.** Числа на 40-м известны (12/- и +6 урона), но ни строки урона,
    # ни строки поглощения в билде нет — значит вопрос такой не задан, и дырки
    # нет. Заодно исчезла асимметрия: оружейная половина той же системы
    # (`Rules.WeaponTypeBonus`) про эти же виды уже молчала.
    #
    # 🔴 **И ГНОМ ИЗ ЭТОГО БЛОКА ВЫБЫЛ 18.09.2026 — посылка снялась, решение
    # нет.** Решение Dan было «пока мы это не показываем», и «пока» было
    # записано буквально: задача 3.210 завела секцию «Резисты»
    # (`DerivedStats.resistances`), то есть у поглощения появился получатель,
    # и 12/18 Гнома считаются ровно как щитовой AC Карлика. Молчать о нём
    # теперь значило бы молчать про посчитанное. Его собственный кейс — ниже,
    # `«у Гнома получатель ПОЯВИЛСЯ»`; здесь остаётся Могучий человек, у чьего
    # урона получателя нет по-прежнему, и остаётся он ОДИН — список из одной
    # расы честнее списка из двух, где вторая уже не про то.
    #
    # ⚠️ Уровни взяты по обе стороны от 40-го НЕ для симметрии: молчание обязано
    # быть полным, а самый вероятный способ сломать правку — уронить эту расу
    # в ветку «уровень мал», которая стоит следующей и ловит `counted: nil`.
    # Отдельный отрицательный ассерт на неё — ниже в теле.
    test "урон молчит, а не называется", %{ruleset: ruleset} do
      for race <- [:half_orc], level <- [1, 39, 40, 41] do
        stats = compute(ruleset, race, level)

        assert racial_gaps(stats) == [], "#{race} #{level}"

        # то же самое поимённо: ни старой формы, ни подмены её ветки ниже
        refute {:missing_data, {:racial_bonus_level, race}} in stats.gaps, "#{race} #{level}"

        # и ни в одно число билда бонус по-прежнему не попал
        assert stats.race_attack_bonus == 0
        assert stats.ac_own_terms == []

        # признак остался в записи — молчат гэпы, а не модель
        refute stats.racial_bonus.modelled?
        assert stats.racial_bonus.counted == nil
      end
    end

    # ⚠️ То же самое при любом содержимом рук, и это не перебор ради перебора:
    # оружие включает сам бонус (`activated?/3`), поэтому кейс выше мог бы
    # зеленеть у кода, который до веток просто не дошёл. Руки перебираются от
    # пустых до невключающего трезубца — ответ обязан не зависеть от них вовсе.
    test "молчат при любом оружии в руках", %{ruleset: ruleset} do
      hands = [
        {"пусто", []},
        {"топор", @armed},
        {"меч", [weapon: :longsword, feats: [:siala_blade_proficiency]]},
        {"трезубец", [weapon: :trident, feats: [:siala_polearm_proficiency]]}
      ]

      # ⚠️ Руки задаются целиком, а не через `geared/2`: тот домешивает `@armed`,
      # и «пусто» перестало бы быть пустым — ровно тот ложно-зелёный, от которого
      # хелпер и оберегает остальные кейсы файла.
      for race <- [:half_orc], level <- [1, 39, 40, 41], {label, gear} <- hands do
        build = %Build{build(race, level) | gear: Gear.new(gear)}

        assert racial_gaps(Rules.compute(build, ruleset)) == [], "#{race} #{level}, #{label}"
      end
    end

    # 🔴 **Положительный контроль к самому выбытию Гнома (задача 3.210).** Без
    # него блок выше зеленел бы и у правки, которая просто вычеркнула расу
    # из списков: молчание «потому что получателя нет» и молчание «потому что
    # посчитано» выглядят на экране одинаково, а значат противоположное.
    #
    # Гном обязан вести себя ровно как три расы с получателем: с оружием
    # в руках — посчитано и тишина, с пустыми — величина известна, а включить
    # её нечем, и билд говорит именно это.
    test "у Гнома получатель ПОЯВИЛСЯ: считается и молчит, как у трёх остальных",
         %{ruleset: ruleset} do
      for level <- [1, 39, 40, 41] do
        armed = compute(ruleset, :dwarf, level)

        assert armed.racial_bonus.modelled?, "#{level}"
        assert is_integer(armed.racial_bonus.counted), "#{level}"
        assert racial_gaps(armed) == [], "#{level}"

