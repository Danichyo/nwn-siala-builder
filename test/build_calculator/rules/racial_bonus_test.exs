                 [{:missing_data, {:racial_bonus_level, race}}],
               "#{race} 39"

        bare = Rules.compute(unarmed(build(race, 40)), ruleset)

        assert racial_gaps(bare) == [{:assumed, {:racial_bonus_variant, race, nil}}],
               "#{race} 40, руки пусты"

        # ...и ровно на том же билде с оружием — тишина, потому что посчитано
