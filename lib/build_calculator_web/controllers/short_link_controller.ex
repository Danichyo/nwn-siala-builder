defmodule BuildCalculatorWeb.ShortLinkController do
  @moduledoc """
  `/s/<key>` — короткая ссылка. Разворачивает её в длинную и уводит на `/b/<code>`.

  ## Почему редирект, а не свой экран

  Своего LiveView здесь нет намеренно, и довод не в экономии кода:

    * **Один экран на код.** `/b/:code` остаётся единственным местом, которое
      декодирует билд, — значит короткий путь не может от него отстать.
    * **Получатель оказывается на самодостаточном адресе.** Длинная ссылка
      несёт билд в себе и переживёт нашу базу; короткая — нет. После редиректа
      в адресной строке лежит именно длинная, то есть тот, кто поделится
      дальше, поделится вечной формой, а не нашей записью.
    * Неизвестный ключ — не третье состояние ошибки внутри экрана просмотра,
      а сообщение на главной.

  ⚠️ **302, а не 301.** Постоянный редирект браузеры кэшируют навсегда, и
  решение «короткая ссылка разворачивается» стало бы необратимым у всех, кто
  однажды по ней прошёл. Кэшируемость тут не стоит запертой двери.
  """
  use BuildCalculatorWeb, :controller

  alias BuildCalculator.ShortLinks

  def show(conn, %{"key" => key}) do
    case ShortLinks.fetch(key) do
      {:ok, %{code: code}} ->
        redirect(conn, to: ~p"/b/#{code}")

      :error ->
        conn
        |> put_flash(:error, "Такой короткой ссылки у нас нет.")
        |> redirect(to: ~p"/")
    end
  end
end
