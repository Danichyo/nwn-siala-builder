      # хелпер и оберегает остальные кейсы файла.
      for race <- [:dwarf, :half_orc], level <- [1, 39, 40, 41], {label, gear} <- hands do
        build = %Build{build(race, level) | gear: Gear.new(gear)}

        assert racial_gaps(Rules.compute(build, ruleset)) == [], "#{race} #{level}, #{label}"
      end
    end

    # 🔴 **Отрицательный контроль ко всему блоку.** Без него тест зеленел бы
    # и у правки, которая вырезала расовые гэпы целиком: три расы с получателем
    # обязаны продолжать говорить там, где сказать есть что.
    #
    # ⚠️ Точек стало две вместо трёх, и середина ушла осознанно (задача 3.102):
    # на 40-м с оружием бонус ПОСЧИТАН, и гэпа там больше нет — про посчитанное
    # признаваться не в чем. Остались две настоящие недостачи, и они разные:
    # ниже 40-го величины не знает никто, а на 40-м с пустыми руками величина
    # известна и бонуса нет, потому что включать его нечем.
    test "расы с получателем оговорки НЕ потеряли", %{ruleset: ruleset} do
