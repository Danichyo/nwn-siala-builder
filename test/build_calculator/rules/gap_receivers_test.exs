      # `class_change_receivers_test.exs` / `siala_feat_layer_test.exs`.
      #
      # ⚠️ 17 → 16 (24.08.2026, задача 3.86): опять МИМО всех трёх слоёв —
      # ушёл `{:not_modelled, :wizard_opposed_school}`, факт про ванильную
      # механику специализации, а не про класс, фит или навык шарда. И ушёл
      # он не решением о границе, как три предыдущих «мимо», а ответом:
      # цена специализации посчитана и напечатана.
      #
      # ⚠️ 16 → 17 (25.08.2026, задача 3.104): и снова МИМО всех трёх слоёв —
      # спор источника про тренировку Исполнения, факт ванильный и про навык.
      assert length(siala.gaps) == 17
    end

    # Проверка самой разметки, а не кода: факт, который ядро СУМЕЛО применить,
    # обязан был двигать число, которое мы печатаем, — иначе метка врёт.
    # Выводится из census без отдельного поля: ours = applied_ours + gaps.
    #
    # ⚠️ Раньше здесь стояло «у фитов та же арифметика держится по ДРУГОЙ
    # причине — там применённые факты метки не несут вовсе», и равенство
    # проверялось на всех трёх слоях разом. **17.08.2026 это перестало быть
    # верно для фитов** (задача «фиты: use/requirements без получателя»):
    # `lay_on_hands/use`, `smile_of_death/use` и `teleportation/use` —
    # ПРИМЕНЁННЫЕ факты (`apply_feat_change/4` хранит «Использование» в
    # структуру всегда, что бы страница ни говорила), и теперь они ЖЕ несут
    # честную метку `special_ability`/`ability_uses`, не наш получатель.
    # Довод теста («применил ⟹ подействовал на печатаемое число») был ВЕРЕН
    # для классов и навыков (там применяется только то, что кто-то осознанно
    # завёл `what`-клозой) и НИКОГДА не был верен для «Использования» фита —
    # оно поле декоративное, `feat.use` не читает ни одно правило вовсе
    # («Carried, never derived from», `apply_feat_change/4`). Равенство
    # держалось не потому, что было доказано, а потому, что до этого дня
    # никто не размечал применённый факт фитов явно.
    test "каждый применённый факт называет получателя, которого мы печатаем — классы и навыки",
         %{siala: siala} do
      for layer <- [:classes, :skills] do
        census = GapReceivers.census(siala)[layer]

        assert census.ours - census.gaps == census.applied, "слой #{layer}"
        assert census.not_ours == census.dropped, "слой #{layer}"
      end
    end

    # Фиты — то же родство чисел, но с поправкой на три декоративных факта:
    # `applied` (177) не равен «применено и подействовало» (174), и разница
    # (3) — это ровно lay_on_hands/smile_of_death/teleportation. `gaps == 0`
    # не изменился, поэтому левая часть равенства из соседнего теста здесь
    # была бы `174 − 0 = 174`, а `applied` — 177: посчитаны оба числа, а не
    # только итог, чтобы разница была видна, а не спрятана внутри вычитания.
    # ⚠️ И `not_ours ≠ dropped` (24 против 21) по той же причине — см. note
    # самого `GapReceivers` (`t:layer/0`): «эти два числа равны только пока
    # каждый применённый факт называет наш получатель», а здесь три
    # применённых факта named не наш.
    test "фиты — ЧЕТЫРЕ применённых факта декоративны, и равенство соседнего теста законно рвётся",
         %{siala: siala} do
      census = GapReceivers.census(siala).feats

      # ⚠️ Было ТРИ (17.08.2026, разметка use-фактов), стало ЧЕТЫРЕ в тот же день:
      # добавился `weapon_finesse/use` с получателем `counted_elsewhere`.
      # «Декоративный» здесь значит «факт применён, но получатель не наш» —
      # у `weapon_finesse` это буквально так: список из 13 оружий ПРИМЕНЁН
      # (лежит в `overrides.json` → `formulas_shard`, читает `Rules.Attack`),
      # просто считает его не эта запись. Отсюда и получатель.
      # ⚠️ 177 → 178 и 173 → 174 (25.08.2026, задача 3.103, запись `artist`
      # в ручном слое), в тот же день 178 → 179 и 174 → 175 (задача 3.106,
      # запись `skill_focus`), и назавтра 179 → 180 и 175 → 176 (задача 3.108,
      # запись `epic_skill_focus`). Обе половины сдвинулись на единицу трижды,
      # поэтому РАЗНИЦА — то самое число декоративных фактов — так и осталась
      # четырёхкратной. Это и есть смысл считать оба числа, а не только итог:
      # прибавка нашего применённого факта разницу не задевает вовсе.
      # ⚠️ 180 → 181 и 176 → 177 (27.08.2026, задача 3.130, запись
      # `devastating_critical`) — четвёртый раз подряд та же арифметика:
      # факт применён и наш (машинное подтверждение уже применённого
      # «отключён», source.kind: "hak"), разница снова не шелохнулась.
      assert census.applied == 181
      assert census.ours - census.gaps == 177
      assert census.applied - (census.ours - census.gaps) == 4
      assert census.not_ours - census.dropped == 4
    end

    # `applied` считается вычитанием, и это верно ровно потому, что
    # `siala_unapplied` — подмножество `siala_changes`. Инвариант загрузчика,
    # без которого число молча поехало бы.
    test "неприменённые факты — подмножество прочитанных, во всех трёх слоях",
         %{siala: siala} do
      for layer <- [:classes, :feats, :skills] do
        stray =
          for record <- siala |> Map.fetch!(layer) |> Map.values(),
              fact <- Map.get(record, :siala_unapplied, []),
              fact not in Map.get(record, :siala_changes, []),
              do: fact

        assert stray == [], "слой #{layer}"
      end
    end

    test "не наши получатели названы поимённо и посчитаны, чаще всего первыми",
         %{siala: siala} do
      counts = GapReceivers.census(siala).classes.not_our_receivers

      refute Enum.any?(counts, &(elem(&1, 0) in GapReceivers.our(siala))),
             "наш получатель не может быть в этом списке"

      # ⚠️ Единица здесь — упоминание получателя, а не факт: у 78 отброшенных
      # фактов 84 упоминания, потому что у шестерых получателей по два. Написать
      # «78» рядом с этой суммой было бы ровно той непроверяемой строкой,
      # на которой проект уже горел (CLAUDE.md §9).
      # ⚠️ 82 → 83 (17.08.2026): прибавил ровно один — штраф вора в скрытности,
      # у которого получатель ОДИН. Факт с двумя прибавил бы двойку, и на этом
      # различии счёт и держится.
      # ⚠️ 83 → 84 (17.08.2026, задача про Мастера оружия): прибавил новый
      # получатель `counted_elsewhere` — ровно один факт, ровно одно упоминание.
      # ⚠️ 84 → 83 (25.08.2026, задача 3.101): убыл ОДИН — факт Тайного лучника
      # про арбалеты применён и из отброшенных ушёл. Упоминание одно, хотя
      # получателей у факта теперь два (`attack_bonus` и `special_ability`):
      # в гистограмму он не попадает вовсе, потому что один из получателей наш.
      assert Enum.sum_by(counts, &elem(&1, 1)) == 83
      assert counts == Enum.sort_by(counts, fn {name, count} -> {-count, name} end)

      # ⚠️ Здесь стояло 11 — стало 14 правкой данных 10.08.2026 по решению Dan
      # («да, это тоже под баффы»): под баффы ушли `Rage` варвара,
      # `Bull's strength` Чёрного стража и `Shadow Evade` Теневого танцора, то
      # есть активируемые КЛАССОВЫЕ умения, а не только заклинания и песня.
      # ⚠️ 15 → 16 (17.08.2026): тем же гейтом по временности ушёл штраф вора
      # в режиме скрытности — режим включается и кончается. Решение то же,
      # четвёртое умение по счёту.
      assert List.first(counts) == {"buff", 16}

      # ⚠️ Счёт идёт по ОТБРОШЕННЫМ фактам, а не по всем — и здесь это ровно
      # то место, где замер 13.08.2026 виден в числе. `custom_items` стоит на 7
      # фактах корпуса, и до замера двое из них несли ещё и `skill_values`, то
      # есть оставались гэпом, поэтому отброшенных было 5. Кейс L1 показал, что
      # прибавка используемого предмета в значение навыка не идёт («Свет плута»:
      # вор с 4 рангами Поиска и INT 8 показывает 3), `skill_values` снят
      # у обоих — и теперь отброшены все 7.
      # Снимок всех 126 — в `Data.ClassChangeReceiversTest`.
      assert {"damage", 9} in counts
      assert {"custom_items", 7} in counts

      # ⚠️ 5 → 6 правкой 10.08.2026, и это иллюстрация к абзацу выше: сам
      # `immunities` в корпусе не двигался (6 фактов и было), но у Теневого
      # танцора он делил запись с `ac`, из-за которого факт был НАШИМ и потому
      # в этот счёт не попадал. `ac` стал `buff` — факт уехал в отброшенные
      # и привёл `immunities` за собой. Счёт по отброшенным, а не по всем.
      assert {"immunities", 6} in counts
    end

    # У слоя фитов свой список категорий, и он обязан быть подмножеством того же
    # словаря: страница печатает один перечень на оба слоя, и категория, которой
    # там нет, ушла бы в число, но не в подпись к нему.
    # ⚠️ Название теста говорит «отброшенных» — до 17.08.2026 это было точно
    # (у фитов `not_ours == dropped`, см. соседний тест про декоративные
    # факты выше), а теперь `not_our_receivers` считает по `not_ours` (24),
    # а не по `dropped` (21): три «декоративных» use-факта применены, но не
    # наши, и в «отброшенные» не входят. Название оставлено — оно всё ещё
    # верно ДЛЯ КЛАССОВ (`class_names`, с которыми сравнивается), а про фиты
    # эта неточность сказана здесь словами, а не переименованием теста.
    test "категории не-наших фактов фитов — из того же словаря, что и у классов",
         %{siala: siala} do
      census = GapReceivers.census(siala)
      class_names = MapSet.new(census.classes.not_our_receivers, &elem(&1, 0))
      feat_names = MapSet.new(census.feats.not_our_receivers, &elem(&1, 0))

      refute Enum.any?(feat_names, &(&1 in GapReceivers.our(siala)))
      assert MapSet.subset?(feat_names, GapReceivers.vocabulary(siala).not_our)

      # Сегодня новых категорий фиты не приносят — значит перечень на странице
      # не меняется от того, что слой добавился, и это сказано числом, а не
      # на глаз.
      #
      # ⚠️ 27 → 28 (17.08.2026): единица здесь — УПОМИНАНИЕ получателя, а не
      # факт, и выросла она на один именно потому, что `improved_evasion` несёт
      # ровно одного получателя (`special_ability`). Факт, у которого их два,
      # прибавил бы двойку — на этом различии счёт и держится.
      # ⚠️ 28 → 31 (17.08.2026, задача «фиты: use/requirements без получателя»):
      # прибавили ТРИ упоминания — по одному на lay_on_hands/use (special_ability),
      # teleportation/use (special_ability) и smile_of_death/use (ability_uses).
      # Все три получателя уже были в словаре класса (`class_names`), поэтому
      # «новых категорий фиты не приносят» остаётся верным — растёт сумма, а не
      # список имён.
      # ⚠️ 31 → 32 (17.08.2026, разметка `weapon_finesse/use`): плюс одно
      # упоминание, `counted_elsewhere`. Получатель тоже не новый — он заведён
      # тем же днём для пары Мастера оружия в `classes.json`, то есть уже стоит
      # в `class_names`, и утверждение «новых категорий фиты не приносят»
      # по-прежнему держится.
      assert MapSet.difference(feat_names, class_names) == MapSet.new()
      assert Enum.sum_by(census.feats.not_our_receivers, &elem(&1, 1)) == 32
    end

    test "у vanilla census пуст по всем трём слоям, а не сломан", %{vanilla: vanilla} do
      empty = %{
        total: 0,
        labelled: 0,
        applied: 0,
        unapplied: 0,
        ours: 0,
        not_ours: 0,
        gaps: 0,
        dropped: 0,
        not_our_receivers: []
      }

      census = GapReceivers.census(vanilla)

      assert census |> Map.keys() |> Enum.sort() == [:classes, :feats, :skills]

      for {layer, counts} <- census,
          do: assert(Map.delete(counts, :reported?) == empty, "слой #{layer}")
    end
  end
