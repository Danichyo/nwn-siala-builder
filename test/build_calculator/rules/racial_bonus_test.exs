    # 15.08.2026**, и это не перестановка, а следствие замера Dan: бонус расы
    # включается оружием в руках, а `ac_naked` считается «без вещей вообще»
    # (`Rules.compute/2` гоняет голый проход по билду с `%Gear{}`). Оружие —
    # вещь, значит голым бонуса нет ни в игре, ни у нас. Оба чтения сходятся
    # к одному ответу, и это тот редкий случай, когда «голым значит голым»
