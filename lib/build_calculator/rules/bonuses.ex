defmodule BuildCalculator.Rules.Bonuses do
  @moduledoc """
  Плумбинг разметки прибавок — то, что у шести читателей было одинаковым.

  Шесть модулей читают шесть файлов **одной схемы** (`priv/rules/vanilla/`:
  `ac_bonuses.json`, `feat_ability_bonuses.json`, `feat_save_bonuses.json`,
  `feat_attack_bonuses.json`, `feat_hp_bonuses.json`,
  `feat_skill_bonuses.json`) и делали это шестью копиями одного кода: чтение
  списка по вердикту, «держит ли персонаж эту запись», сбор гэпов из
  отвергнутых, `effect_coverage`, сторона капа. Появлялись по одной за задачу
  (HP — 1.9, характеристики — 3.1, AC — 3.11, сейвы — 1.12a, атака — 1.12b).

  ⚠ **Задача 3.21 свела пять из шести, и остановилась не там, где хотела.**
  Схема двух файлов — HP и навыков — отличалась в **данных**: загрузчик вливал их
  записи в поля фита, где не оставалось ни вердикта, ни вида источника, ни
  стороны капа. Правку данных 3.21 делать права не имела, и разница честно
  висела оговоркой в moduledoc `Rules.FeatBonuses`. Закрыто задачей 3.25
  (10.08.2026): схема приведена к общей, оба файла читаются отсюда, шестая копия
  обхода (`owned_feat_fields/4`) удалена. Стоила она не только дублирования —
  оговорка `small_stature` не доезжала ни до одного билда, потому что гейт по
  владению фитом расовых склонностей не содержит, а вида источника `race_feat` у
  скилловой разметки не было вовсе.

  ## Что здесь есть и чего здесь нет

  Здесь — **только плумбинг**. Смысл стата остаётся в его собственном модуле,
  и это не оговорка, а условие задачи: типы прибавок AC и правило
  нескладывания однотипных, три цели у сейвов, две формы у характеристик,
  смена формулы у атаки — всё это специфика, которую слияние обязано было
  оставить видимой. Поэтому здесь нет ни одной функции, которая знает про
  `type`, `saves`, `ability` или `condition`.

  Проверка простая: испорти что-нибудь здесь — пострадают все шесть статов
  сразу; испорти `amount/3` в `Rules.SaveBonuses` — пострадают только сейвы.
  Ровно за эту границу шесть копий и платили.

  ## Ничего здесь не знает игровых чисел

  Ни одного фита, класса, навыка или расы по имени, ни одного потолка
  литералом: потолки приходят из `ruleset.stat_caps` через `Rules.Caps`,
  записи — из `ruleset`, ключ файла разметки передаёт вызывающий.

  ## Один клип, а не один клип на источник

  `clip/3` — единственная реализация потолка на прибавки в ядре. До этой
  задачи их было две (`clip_attack/2` и `clip_saves/4` в `Rules`), и именно
  на этом месте уже жили **два** бага: сейвы клипались по половинке (вещи
  отдельно, Spellcraft отдельно — фактически +40 при потолке +20), атака
  клипалась по каждому источнику. Две формы одного правила — это две
  возможности разойтись, а расходятся они молча.
  """

  alias BuildCalculator.Rules.{Build, Caps, GapReceivers}

  @typedoc """
  Ключ ruleset'а, под которым лежит разобранный файл разметки —
  `:ac_bonuses`, `:ability_bonuses`, `:save_bonuses`, `:attack_bonuses`,
  `:hp_bonuses`, `:skill_bonuses`.

  Передаётся аргументом, а не выводится из стата: связка «стат → файл» живёт
  у стата, и дублировать её здесь значило бы завести второе место, где она
  может разойтись с первым.
  """
  @type markup :: atom()

  @typedoc """
  Запись разметки, насколько она интересна плумбингу.

  Всё остальное — `type` у AC, `saves` у сейвов, `condition` у атаки,
  `skills` и `counted_for_classes` у навыков, `amount` у всех — читает сам стат.
  """
  @type entry :: %{
          :id => atom(),
          :source => {atom(), atom()},
          :verdict => atom(),
          optional(any()) => any()
        }

  @doc """
  Записи с вердиктом `applied` — те, чья прибавка идёт в число.

  Пустой список, если файла разметки нет вовсе: отсутствие файла — это «нет
  таких прибавок», а не ошибка. Порядок — как в самих данных, и это часть
  контракта: разбор в интерфейсе печатает термы в том порядке, в котором их
  назвал человек, писавший файл.
  """
  @spec applied(map(), markup()) :: [entry()]
  def applied(ruleset, markup), do: half(ruleset, markup, :applied)

  @doc """
  Записи с вердиктом `not_modelled` — те, чью прибавку модель считать
  отказывается и обязана назвать по имени.

  ⚠ Не «остальные». Вердиктов четыре, и два других сюда не попадают:
  `counted_elsewhere` (прибавка уже приходит другим путём — девять расовых
  `skill_affinity_*` пришли бы вторым разом и дали бы эльфу +4 Spot) и
  `not_a_*` (запись вообще не про этот стат). Молчание про них — не дыра,
  а верный ответ, и именно поэтому отвергнутые пишутся в данные **с
  вердиктом**, а не отсутствием записи.
  """
  @spec rejected(map(), markup()) :: [entry()]
  def rejected(ruleset, markup), do: half(ruleset, markup, :unmodelled)

  @doc """
  Записи с вердиктом `counted_elsewhere` — те, чей факт уже учтён **другой**
  записью того же файла или другим местом ядра, и `owned_by` называет, где.

  Ни в одно число сами не идут: посчитать их вторым разом значило бы задвоить
  прибавку (девять расовых `skill_affinity_*` дали бы эльфу +4 Spot вместо +2),
  а отвергнуть вторым разом — напечатать два гэпа про один и тот же факт.
  Единственное, на что они отвечают, — `whole_effect_counted?/3`: посчитан ли
  эффект фита **где-то**, если не здесь.

  ⚠ **До 14.08.2026 загрузчик их выбрасывал**, и это было слепое пятно, а не
  упрощение: запись, говорящая «учтено вон там», доезжала до ядра как
  отсутствие записи — неотличимо от фита, про который файл вообще не
  спрашивали. Ровно поэтому у каждого билда с Мастером оружия висела оговорка
  «прибавку от `Weapon of choice` не считаем» рядом с посчитанной колонкой его
  класса, и смена вердикта записи ничего не меняла.
  """
  @spec counted_elsewhere(map(), markup()) :: [entry()]
  def counted_elsewhere(ruleset, markup), do: half(ruleset, markup, :counted_elsewhere)

  defp half(ruleset, markup, key), do: Map.get(Map.get(ruleset, markup) || %{}, key, [])

  @doc """
  Записи `applied`, которые этот персонаж действительно держит на `level`.

  В порядке самих данных. Дальше стат сам превращает запись в терм: у AC это
  одно число с типом, у сейвов — до трёх термов на запись, у характеристик —
  сколько абилок назвала таблица.

  ⚠ `level` не украшение: фит, взятый на 27-м, не имеет права менять то, что
  было посчитано на 26-м. Дельта считается как разность двух полных
  `compute` по обрезанным билдам, поэтому «держит ли» — всегда вопрос про
  **тот** уровень, а не про готовый билд.
  """
  @spec held(Build.t(), map(), markup(), non_neg_integer()) :: [entry()]
  def held(%Build{} = build, ruleset, markup, level),
    do: held_half(build, ruleset, applied(ruleset, markup), level)

  @doc """
  То же для **отвергнутой** половины — записи, чью прибавку модель считать
  отказывается, из тех, что этот персонаж держит **и про которые нам есть что
  сказать**.

  Отличается от `rejected_ids/5` тем, что отдаёт **записи, а не имена**, и это
  нужно ровно одному стату: у навыков оговорка адресная — она ложится в тот
  навык, которого недостаёт, а какие это навыки, знает только сама запись
  (`Rules.Skills.feats_by_skill/3`). Остальным четырём хватает имени, и они
  зовут `rejected_ids/5`, который выражен через эту же функцию.

  ## Два вопроса, а не один (17.08.2026)

  Вердикт `not_modelled` говорит «эту прибавку модель не считает». Гэп говорит
  «в нашем ОТВЕТЕ дырка» — а это верно, только если получатель прибавки вообще
  наш (CLAUDE.md §9, решение Dan 10.08.2026: «то, что включается и кончается,
  — не наше»). Ярость варвара прибавляет силу, AC и сейвы, и все три прибавки
  **временные**: игроку сообщали про три дырки в ответе, которого никто не
  ждёт. Поэтому здесь два гейта подряд:

    * `held?/5` — **держит ли** персонаж источник записи;
    * `GapReceivers.bonus_ours?/2` — **печатаем ли** мы то, что запись меняет.

  ⚠ Гейт стоит именно здесь, в единственной воронке шести статов, а не у
  каждого из них. Через `held_rejected/4` проходят обе формы оговорки — и
  корпусная (`rejected_ids/5` → гэпы AC, атаки, сейвов, характеристик, HP), и
  адресная (`Rules.Skills.feats_by_skill/3` → строка навыка), — а два списка
  про одно и то же, отвечающие по-разному, хуже, чем оба неверных. До этой
  правки они и расходились: `small_stature` уже пропал из `ruleset.gaps` и
  всё ещё висел в панели навыка.

  ⚠ **Направление ошибки — в сторону показа**, и оно всё то же: запись **без**
  `affects` гэпом остаётся, ruleset без словаря получателей (`vanilla`) не
  фильтрует ничего. Молчание про непосчитанное дороже лишней строки.

  ⚠ `rejected/2` фильтра не знает и знать не должен: вердикт — свойство
  записи, а «наш ли получатель» — свойство пары «запись + ruleset». Веб-слой
  ищет по этому списку величину рядом с уже выданной оговоркой
  (`Builder.Labels`), и отфильтрованный список сделал бы подпись немой.
  """
  @spec held_rejected(Build.t(), map(), markup(), non_neg_integer()) :: [entry()]
  def held_rejected(%Build{} = build, ruleset, markup, level) do
    our = GapReceivers.our(ruleset)

    build
    |> held_half(ruleset, rejected(ruleset, markup), level)
    |> Enum.filter(&GapReceivers.bonus_ours?(&1, our))
  end

  defp held_half(build, ruleset, records, level) do
    owned = Build.feats_owned(build, ruleset, level)

    for record <- records, held?(record.source, build, ruleset, owned, level), do: record
  end

  @doc """
  Держит ли персонаж источник записи на `level`.

  Пять видов источника, и все пять читаются по-разному — это и есть та
  часть, которая была скопирована четыре раза:

    * `{:feat, id}` — фит считается **владением**, а не взятием слотом:
      фит есть фит, как бы он ни пришёл. `Divine grace` и `Dragon abilities`
      приходят выдачей класса, `Armor skin` может прийти с вещи (задача 3.3);
    * `{:class, id}` — от собственных уровней класса, взятых к `level`;
    * `{:skill, id}` — как только куплен хоть один ранг. Без этого условия
      каждый билд в игре носил бы «песню барда в AC не считаем», а оговорка,
      которая стоит на всём, не стоит ни на чём;
    * `{:race_feat, id}` — от расы, и **никогда** от `Build.feats_owned/3`:
      расовых бонусных фитов там нет, а расширение этой функции молча
      изменило бы каждую проверку требований в приложении (у Карлика
      `spell_focus` — расовая склонность);
    * `{:race, id}` — просто эта раса.

  ⚠ **Без catch-all, сознательно.** Какие виды вообще могут дойти до записи,
  проверяет загрузчик (`@ac_bonus_sources` и его четыре родственника, все
  падают на **компиляции**), поэтому несовпавший вид — это сломанная сборка,
  а не живой запрос. Ветка-заглушка, возвращающая `false`, превратила бы это
  ровно в ту поломку, от которой вся разметка и заведена: прибавку, которая
  молча не считается.
  """
  @spec held?({atom(), atom()}, Build.t(), map(), MapSet.t(atom()), non_neg_integer()) ::
          boolean()
  def held?(source, build, ruleset, owned, level)

  def held?({:feat, id}, _build, _ruleset, owned, _level), do: MapSet.member?(owned, id)

  def held?({:class, id}, build, _ruleset, _owned, level),
    do: build |> Build.class_levels(level) |> Map.get(id, 0) > 0

  def held?({:skill, id}, build, _ruleset, _owned, level),
    do: Build.skill_ranks(build, id, level) > 0

  def held?({:race_feat, id}, %Build{race: race}, ruleset, _owned, _level) do
    case Map.get(ruleset.races || %{}, race) do
      %{bonus_feats: feats} -> id in feats
      _ -> false
    end
  end

  def held?({:race, id}, %Build{race: race}, _ruleset, _owned, _level), do: race == id

  # ⚠️ Здесь стояла `owned_feat_fields/4` — «фиты, которыми персонаж владеет и у
  # которых заполнено такое-то поле». Удалена 10.08.2026 задачей 3.25, и не за
  # ненадобность в одном месте, а потому что **исчезла вторая форма, в которой
  # разметка приходила в ядро**: загрузчик вливал `feat_hp_bonuses.json` и
  # `feat_skill_bonuses.json` в поля фита (`hp_bonus`, `skill_bonuses`, …), где у
  # записи не оставалось ни `verdict`, ни `source`, ни `cap`, и `applied/2` с
  # `held/4` им поэтому не подходили. Теперь оба файла — списки записей, как
  # четыре остальных, и обход у шести статов один: `held/4` и `held_rejected/4`.
  #
  # Что при этом изменилось в наблюдаемом поведении: порядок. Обход шёл по
  # **возрастанию id фита**, а `held/4` идёт в порядке самих данных — это часть
  # контракта `applied/2` (человек, писавший файл, назвал термы в том порядке, в
  # котором их надо печатать). У HP это переставило разбор: `Toughness` теперь
  # стоит перед `Epic toughness`, как в файле, а не после него по алфавиту.

  @doc """
  Сколько уровней этого класса набрано — то, от чего считаются все таблицы
  «по уровню класса».

  Арность на выбор: `/2` спрашивает про готовый билд, `/3` — про состояние на
  `level`.

  ⚠ Это не косметика: до задачи 3.21 характеристики читали таблицу
  **с учётом уровня**, а AC, сейвы и атака — по готовому билду, и различие
  жило четырьмя копиями одной строки, где заметить его было нечем. Ответы
  совпадают ровно потому, что три копии зовутся с `Build.character_level/1`;
  один вопрос — одна функция, и тогда расхождение становится видимым выбором
  арности, а не случайностью.
  """
  @spec class_level(Build.t(), atom()) :: non_neg_integer()
  def class_level(%Build{} = build, class),
    do: class_level(build, class, Build.character_level(build))

  @spec class_level(Build.t(), atom(), non_neg_integer()) :: non_neg_integer()
  def class_level(%Build{} = build, class, level),
    do: build |> Build.class_levels(level) |> Map.get(class, 0)

  @doc """
  Значение таблицы на **высшей достигнутой ступени** — чтение «в таблице
  итоги», не «в таблице приросты».

  Так печатают свои колонки таблицы прогрессии классов на вики: `Sacred
  defense` стоит `+1` на 2-м уровне класса и `+2` на 4-м, и это `+2`, а не
  `+3`. Ниже первой ступени прибавки нет вовсе — монах 4 на Сиале имеет
  мудрость в AC и ни одного очка из своей классовой колонки, и ровно поэтому
  это две разные записи. За последней ступенью держится последнее названное
  значение: таблицы вики кончаются на 30-м или 40-м уровне класса, а кап
  Сиалы 41 — продолжать прогрессию значило бы выдумать число.

  ⚠ **Противоположное чтение — тоже настоящее**, и живёт у характеристик:
  `ability_at_class_level` ступени **суммирует** (`+2` силы на 2-м уровне и
  снова на 4-м — это `+4`). Обе колонки приходят с одной страницы вики и
  напечатаны по-разному, поэтому каждый файл данных объявляет своё чтение, а
  здесь их две функции, а не одна с флагом: флаг пришлось бы угадывать.
  """
  @spec total_at_step(%{pos_integer() => integer()}, non_neg_integer()) :: integer()
  def total_at_step(table, reached) do
    table
    |> Enum.filter(fn {step, _value} -> step <= reached end)
    |> Enum.max_by(fn {step, _value} -> step end, fn -> {0, 0} end)
    |> elem(1)
  end

  @doc """
  Термы, сложенные в одно число — `key` называет, где у терма величина
  (`:ac` у брони, `:bonus` у остальных).
  """
  @spec sum([map()], atom()) :: integer()
  def sum(terms, key), do: Enum.reduce(terms, 0, &(Map.fetch!(&1, key) + &2))

  @doc """
  Термы, сложенные по цели — `%{ability => bonus}`, `%{save => bonus}`.

  Цель, которую никто не поднял, **отсутствует**, а не равна нулю: «здесь
  ничего» и «вообще ничего» — разные утверждения, и вызывающий должен уметь
  их различить, не сравнивая с нулём.
  """
  @spec group_sum([map()], atom(), atom()) :: %{atom() => integer()}
  def group_sum(terms, group_key, value_key) do
    Enum.reduce(terms, %{}, fn term, acc ->
      value = Map.fetch!(term, value_key)

      Map.update(acc, Map.fetch!(term, group_key), value, &(&1 + value))
    end)
  end

  @doc """
  Идентификаторы отвергнутых записей, которые этот персонаж держит.

  То, из чего билд делает `{:not_modelled, {…, id}}`: ярость, стойка,
  прибавка против одного вида врагов, прибавка, включаемая раз в день. Все
  они либо выключены по умолчанию, либо уже́ той прибавки, что показало бы
  плоское число, — и в обоих случаях модель обязана назвать источник, а не
  промолчать.

  Опции:

    * `:filter` — предикат на **запись**, не на id. Атаке нужен именно он:
      её отвергнутые делятся на «зависит от оружия» (это снимет армори,
      задача 3.5) и всё остальное, а таблица по уровням класса не стоит
      оговорки, пока билд не дошёл до её первой ступени;
    * `:uniq?` — свернуть повторы по id, по умолчанию `true`.

  ⚠ `uniq?: false` существует для AC и это **сохранённая асимметрия, а не
  улучшение**. Его сбор гэпов никогда не сворачивал повторы, у трёх
  остальных `uniq: true` стоял с самого начала; сегодня в данных
  повторяющихся id нет, поэтому оба чтения дают одно и то же. Выравнивать
  наугад в рефакторинге нечего: разница ничего не меняет ровно до того дня,
  когда в файле появится вторая запись про один источник, — и тогда это
  вопрос к данным, а не к коду.
  """
  @spec rejected_ids(Build.t(), map(), markup(), non_neg_integer(), keyword()) :: [atom()]
  def rejected_ids(%Build{} = build, ruleset, markup, level, opts \\ []) do
    filter = Keyword.get(opts, :filter, fn _record -> true end)

    ids =
      for record <- held_rejected(build, ruleset, markup, level),
          filter.(record),
          do: record.id

    if Keyword.get(opts, :uniq?, true), do: Enum.uniq(ids), else: ids
  end

  @doc """
  Гэпы из отвергнутой половины разметки — `rejected_ids/5`, обёрнутые формой.

  `form` получает id и возвращает готовый гэп, потому что форма — это
  словарь стата, а не плумбинга: `{:not_modelled, {:ac_bonus, id}}`,
  `{:not_modelled, {:save_bonus, id}}`, у атаки их две. Каждая форма
  зарегистрирована в `Rules.Vocabulary`, и сторож подписей роняет сборку,
  если у неё нет русского текста.
  """
  @spec gaps(Build.t(), map(), markup(), non_neg_integer(), (atom() -> tuple()), keyword()) ::
          [tuple()]
  def gaps(%Build{} = build, ruleset, markup, level, form, opts \\ []) do
    for id <- rejected_ids(build, ruleset, markup, level, opts), do: form.(id)
  end

  @doc """
  Посчитана ли **вся** прибавка этого фита — то есть можно ли перестать
  говорить «прибавку от фита в статы не считаем».

  Спрашивает `Rules.FeatChoices.gaps/3` про повторяемый фит. Как только
  десять очков `Great strength` посчитаны **и названы** в разборе, эта
  оговорка спорит с термом, который игрок видит на экране, а оговорка,
  спорящая с экраном, хуже отсутствующей.

  ⚠ Утверждение — данных (`effect_coverage: "whole_feat"`), и **никогда** не
  выводится из того, что прибавка применена. `Snake blood` и `Strong soul`
  применены и всё равно отвечают `false`: у каждого есть второй, более
  узкий эффект (против яда, против магии смерти), который не считает никто,
  — в данных это `effect_coverage: "partial"`, и оговорка обязана продолжать
  чего-то стоить именно для них.

  ## Считается — не значит «этой записью» (14.08.2026)

  Утверждений тут два, и раньше читалось только первое:

    * фит **объявил**, что посчитан целиком (`covers_feat?`) — это данные;
    * его число действительно доезжает до билда. Раньше это значило «запись
      `applied`»; теперь ещё и «запись `counted_elsewhere`, чей `owned_by`
      называет `applied`-запись этого же файла».

  Второй путь — про `Weapon of choice`. Сам фит числа не даёт вовсе: он
  **назначает оружие**, на которое действует колонка «AB bonus» Мастера
  оружия, и она-то и посчитана (`owned_by: "weapon_master"`). Пока
  `counted_elsewhere` не читался, у каждого билда с этим фитом висела
  оговорка «прибавку от фита в статы не считаем» — рядом с термом
  `weapon_master +7` на том же экране.

  ⚠ `owned_by`, указывающий на **механизм** ядра или на задачу
  (`attack_ability`, `Rules.Progression`, `1.12b`), не резолвится и оговорку
  не снимает. Это осознанно строгая сторона: «посчитано где-то в ядре» —
  утверждение, которое этот файл проверить не может, а `applied`-запись рядом
  — может.
  """
  @spec whole_effect_counted?(map(), markup(), atom()) :: boolean()
  def whole_effect_counted?(ruleset, markup, feat_id) do
    claims =
      for record <- applied(ruleset, markup) ++ counted_elsewhere(ruleset, markup),
          record.source == {:feat, feat_id},
          record.covers_feat?,
          do: record

    Enum.any?(claims, &counted?(&1, ruleset, markup))
  end

  defp counted?(%{verdict: :applied}, _ruleset, _markup), do: true

  defp counted?(%{owned_by: owner}, ruleset, markup) when is_binary(owner) do
    Enum.any?(applied(ruleset, markup), &(to_string(&1.id) == owner))
  end

  defp counted?(_record, _ruleset, _markup), do: false

  @doc """
  Один клип потолка — единственный в ядре.

  `sides` — `[{под_капом?, значение}]`; сторону вызывающий уже определил, у
  механизма по виду источника (`Caps.covers_source?/3`), у собственного терма
  по самой записи (`Caps.covers_record?/3`). Здесь она не решается: у
  `Divine grace` и `Sacred defense` одна форма записи и разные ответы, так
  что вывести сторону из вида нельзя, и попытка была ошибкой дважды.

  Возвращает `%{total:, clipped:, capped?:}` — весь вклад после потолка
  (срезанная часть плюс та, что лежит поверх), сколько потолок забрал
  (`0` или отрицательное) и укусил ли он вообще.

  ⚠ Слагаемые поверх потолка прибавляются **после** клипа и в нём не
  участвуют, в этом весь смысл: +1 от фита на билде, уже стоящем на +20, —
  это +1, а не ничто (09.08.2026, Dan). И сам клип остаётся **одним**
  `Caps.clamp/3` по сумме, никогда по источнику.
  """
  @spec clip(map(), Caps.stat(), [{boolean(), integer()}]) :: %{
          total: integer(),
          clipped: integer(),
          capped?: boolean()
        }
  def clip(ruleset, stat, sides) do
    {inside, outside} = Enum.split_with(sides, &elem(&1, 0))
    raw = sum_sides(inside)
    {clamped, capped?} = Caps.clamp(ruleset, stat, raw)

    %{total: clamped + sum_sides(outside), clipped: clamped - raw, capped?: capped?}
  end

  defp sum_sides(sides),
    do: Enum.reduce(sides, 0, fn {_under_cap?, value}, acc -> acc + value end)

  @doc """
  Какой стороны потолка слагаемое, **где этого никто не написал**, а ядру
  всё равно пришлось выбрать.

  Две формы, потому что данные называют сторону на двух уровнях, и оговорка
  обязана называть то, о чём она: `{:cap_covers_source, stat, kind}` про
  механизм (вещи, расовый бонус шарда, правило навыка) и
  `{:cap_covers_entry, stat, id}` про одну запись разметки. Одна форма на
  оба печатала бы «вид источника» над вопросом про конкретный фит.

  ⚠ **Сегодня ни одна из них не появляется, и это результат работы, а не
  дыра.** 09.08.2026 три записи были `assumed` — `Small stature`, `Lucky`,
  `Dark blessing` — и список Dan закрыл все три. Механизм оставлен, потому
  что «никто этого не писал» должно жить не в комментарии: в день, когда
  придёт запись без объявленной стороны, билд скажет об этом сам, а не
  выберет молча.

  ⚠ Только те слагаемые, по которым у билда **ненулевая** прибавка: оговорка
  про вопрос, который не возникает, — шум. И никогда не при условии, что
  потолок **укусил**: кап атаки сегодня недостижим (под ним с 10.08.2026
  остался один расовый бонус Сиалы, максимум +9 против +20 — задача 3.22;
  всех трёх источников вместе было +16), а допущение, видимое только когда
  потолок кусает, — это ровно допущение, которого никто не видит.
  """
  @spec cap_side_gaps(map(), Caps.stat(), markup(), keyword(integer()), [map()]) :: [tuple()]
  def cap_side_gaps(ruleset, stat, markup, mechanisms, terms) do
    from_mechanisms =
      for {source, value} <- mechanisms,
          value != 0,
          Caps.assumed_source?(ruleset, stat, source),
          uniq: true,
          do: {:assumed, {:cap_covers_source, stat, source}}

    from_records =
      for term <- terms,
          term.bonus != 0,
          assumed_term?(ruleset, stat, markup, term),
          uniq: true,
          do: {:assumed, {:cap_covers_entry, stat, term.id}}

    from_mechanisms ++ from_records
  end

  # Терм несёт сторону, но не запись, от которой она пришла, — поэтому запись
  # ищется заново, чтобы спросить, была ли сторона **объявлена** или выбрана.
  # Читается из ruleset'а, а не носится на терме: `under_cap?` — арифметика,
  # нужная клипу на каждом билде, `assumed?` — оговорка, нужная почти ни на
  # одном.
  defp assumed_term?(ruleset, stat, markup, term) do
    Enum.any?(
      applied(ruleset, markup),
      &(&1.source == term.source and Caps.assumed_record?(ruleset, stat, &1))
    )
  end
end
