defmodule Mix.Tasks.Assets.Test do
  @shortdoc "Гоняет JS-тесты колокированных LiveView-хуков (node --test + happy-dom)"

  @moduledoc """
  Тестирует `.FeatInfo`/`.StatPop` — колокированные хуки в
  `BuildCalculatorWeb.BuilderComponents` (задача 3.138 П1, `AGENT_QUEUE.md`;
  разбор архитектуры — там же и в moduledoc `stat_pop/1`).

      mix assets.test

  `mix precommit` зовёт эту задачу сам, после `compile --warnings-as-errors`.

  ## Что именно тестируется

  Не исходный код хука (он живёт внутри `~H\"""...\"""` в `.ex`-файле и не
  является отдельным исполняемым JS сам по себе), а **скомпилированный
  бандл** — тот же `_build/<env>/phoenix-colocated/build_calculator/…`,
  который `assets/js/app.js` импортирует в браузере
  (`import {hooks as colocatedHooks} from "phoenix-colocated/build_calculator"`).
  Копия исходника в отдельном JS-файле тестировала бы строку, похожую на
  хук, а не сам хук — LiveView компилирует его из HEEx прямо на этапе сборки,
  и `phx-hook=".Name"` разворачивается в имя МОДУЛЯ, чей ШАБЛОН несёт
  атрибут (не модуля, где физически стоит `<script>`) — на этом уже горели
  однажды: хук молча не монтировался, `Phoenix.LiveViewTest` JS не исполняет,
  поэтому не упало ничего. `assets/test/support/hooks.mjs` читает бандл
  через сгенерированный `index.js` — единственную стабильную точку входа
  (имена самих файлов хешированы и зависят от номера строки в исходнике).

  Значит порядок важен: **эта задача обязана идти после `mix compile`**
  для актуального `MIX_ENV` — `_build/<env>/phoenix-colocated/…` появляется
  только тогда. `mix precommit` уже ставит её вторым шагом; при ручном
  вызове задача сама подставит текущий `Mix.env()` дочернему процессу
  через `MIX_ENV`, но полагается на то, что `_build/<env>/…` уже собран.

  ## Что покрыто (регрессия, не всё подряд)

  Не «покрыть 819 строк колокированных хуков», а закрыть три дефекта,
  каждый из которых раньше находился только руками (CDP-прогонами,
  24.08.2026):

    * `.FeatInfo`: кнопка «×» однажды не закрывала панель ни разу —
      `close({restoreFocus: true})` фокусирует триггер, а на триггере свой
      слушатель `focus`, открывающий панель заново (чинится флагом
      `suppressAutoOpen`);
    * `DISMISS_GUARD_MS` — пассивные сигналы закрытия (клик мимо, скролл,
      курсор ушёл) не должны срабатывать сразу после открытия, а активные
      (Esc, «×», повторный клик) обязаны срабатывать немедленно;
    * `.StatPop`: ниже порога 940px хук вообще не вешает слушателей — разбор
      не становится разметкой, а не прячется CSS-ом, — и решение
      принимается заново при каждом живом пересечении порога, не только
      при монтировании.

  Каждый из трёх проверен положительным контролем при написании (дефект
  временно воспроизведён правкой источника, тест честно покраснел, код
  возвращён, тест снова позеленел) — подробности в отчёте задачи 3.138 П1,
  не в этом файле: тут им не место, а комментарии в самих хуках
  (`builder_components.ex`) остаются источником правды про КАЖДЫЙ дефект.

  ## Почему `node:test` + happy-dom, а не vitest/jsdom

  Прогонщик — не зависимость: Node 24 (минимум, на котором это писалось)
  несёт `node:test`/`node:assert` встроенными. DOM нужен настоящий — хуки
  создают узлы, вешают глобальные слушатели, читают `matchMedia` и
  `getBoundingClientRect` — заглушки руками для 415-строчного `.FeatInfo`
  были бы длиннее самого теста. `happy-dom` — единственная зависимость
  (`assets/package.json`) вместо ~200 пакетов у vitest.
  """
  use Mix.Task

  @impl Mix.Task
  def run(_args) do
    ensure_npm!()

    unless File.dir?("assets/node_modules") do
      Mix.raise("""
      assets/node_modules не найден.

      JS-тесты не пропускаются молча — сторож, который иногда ничего
      не проверяет, хуже отсутствующего (CLAUDE.md §9, задача 3.132: так
      шесть строк едва не уехали на прод по-английски мимо сторожа переводов).

      Запусти "mix assets.test.setup" (или "mix setup" целиком) и повтори.
      """)
    end

    env_name = to_string(Mix.env())
    Mix.shell().info("[assets.test] npm test (assets/, MIX_ENV=#{env_name})")

    {_, status} =
      System.cmd("npm", ["test"],
        cd: "assets",
        env: [{"MIX_ENV", env_name}],
        into: IO.stream(:stdio, :line),
        stderr_to_stdout: true
      )

    if status != 0 do
      Mix.raise("JS-тесты упали (npm test в assets/ вышел с кодом #{status})")
    end
  end

  defp ensure_npm! do
    case System.find_executable("npm") do
      nil -> Mix.raise("нужен npm (идёт с Node.js) — им гоняются JS-тесты")
      _ -> :ok
    end
  end
end
